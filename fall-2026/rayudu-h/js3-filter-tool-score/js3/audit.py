"""The reject audit, recomputed from the committed files: the samples, Hemanth's verdicts, and
the filter. It uses the AUDIT labels only. The held-out keys are refused here (FILTER.md W5).

    python -m js3 audit      -> audit/audit-results.md (every number AUDIT.md cites)
"""
from __future__ import annotations

import collections
import copy
import json

from . import ROOT, corpus, filterdoc, labeling, score, stats

CANT_TELL = "can't tell"
STRATA = (("audit_random_rejects", "random rejects (uniform; the only part that supports a rate)"),
          ("audit_closest", "closest calls (5 on each side of the threshold; supports no rate)"),
          ("audit_kept", "random kept"))


def load_inputs(label_set: str = "first"):
    s = json.loads((ROOT / "audit" / "samples.json").read_text())
    labels = labeling.read_labels(ROOT / "audit" / "labels.csv")
    if label_set == "corrected":
        from . import relabel
        labels = {k: v for k, v in relabel.corrected_labels().items() if k in labels}
    heldout = set(s["heldout"])
    audit_keys = [k for name, _ in STRATA for k in s[name]]
    if set(audit_keys) & heldout:
        raise ValueError("audit and held-out sets overlap")
    return s, labels, heldout, audit_keys


def wrong(decision: str, verdict: str) -> bool:
    return (decision == "rejected" and verdict == "relevant") or (decision == "kept" and verdict == "not relevant")


def confusion(results: dict, labels: dict, keys) -> dict:
    m = collections.Counter()
    for k in keys:
        v = labels[k]["verdict"]
        if v == "can't tell":
            m["cant_tell"] += 1
            continue
        m[{("kept", "relevant"): "TP", ("kept", "not relevant"): "FP",
           ("rejected", "relevant"): "FN", ("rejected", "not relevant"): "TN"}[(results[k]["decision"], v)]] += 1
    m["correct"] = m["TP"] + m["TN"]
    m["n"] = m["TP"] + m["FP"] + m["FN"] + m["TN"]
    return dict(m)


EXPERIENCE_KEYS = ("experience_years_min", "experience_excludes", "experience_range_low")


def versions(current: dict = None) -> dict:
    """Each released filter version, rebuilt from the current FILTER.md block by removing later rules.
    v1.2 = the block as written; v1.1 = without R17 (the experience rule); v1.0 = also without X1."""
    current = current or filterdoc.load()
    v11 = copy.deepcopy(current)
    for k in EXPERIENCE_KEYS:
        v11.pop(k, None)
    v11["filter_version"] = "1.1"
    v10 = copy.deepcopy(v11)
    v10["seniority_ignore_phrases"], v10["role_ignore_phrases"] = [], []
    v10["filter_version"] = "1.0"
    return {"1.0": v10, "1.1": v11, "1.2": current}


def variants(current: dict) -> list:
    """v1.0 and the four measured changes X1-X4 (all relative to v1.0, as measured on Nov 22)."""
    v10 = versions(current)["1.0"]
    x1 = copy.deepcopy(v10); x1["seniority_ignore_phrases"] = ["Technical Staff"]
    x2 = copy.deepcopy(v10); x2["weights"]["seniority"] = 0.0
    x3 = copy.deepcopy(v10); x3["require_skill"] = False
    x4 = copy.deepcopy(v10); x4["role_ignore_phrases"] = ["Data Center", "Datacenter"]
    return [("v1.0", v10, "as written before the audit"),
            ("X1", x1, '"Staff" inside "Technical Staff" is not seniority (accepted: v1.1)'),
            ("X2", x2, "no seniority penalty (rejected)"),
            ("X3", x3, "no skill requirement (rejected)"),
            ("X4", x4, '"Data Center" is not the role word "Data" (rejected)')]


def run(write: bool = True, label_set: str = "first") -> str:
    s, labels, heldout, audit_keys = load_inputs(label_set)
    c = corpus.load()
    current = filterdoc.load()
    vs = versions(current)
    base = {k: score.score(p, variants(current)[0][1]) for k, p in c["postings"].items()}
    L = [f"# Audit results (generated by `python -m js3 audit{' --labels corrected' if label_set == 'corrected' else ''}`; "
         "audit labels only, held-out refused)", "",
         f"**Labels: {'CORRECTED: second-pass verdicts (experience shown) where they exist, else first-pass' if label_set == 'corrected' else 'first pass, as committed Nov 22'}.**", "",
         f"Samples: `audit/samples.json` (seed {s['seed']}); verdicts: `audit/labels.csv`; filter v1.0 "
         "(the version the samples were drawn from).", ""]

    # 1. strata
    L += ["## 1. Hand verdict vs filter v1.0, by stratum", "",
          "| stratum | n | filter wrong | wrong / n | Wilson 95% |", "|---|---:|---:|---:|---|"]
    for name, desc in STRATA:
        ks = s[name]
        bad = sum(1 for k in ks if wrong(base[k]["decision"], labels[k]["verdict"]))
        lo, hi = stats.wilson(bad, len(ks))
        L.append(f"| {desc} | {len(ks)} | {bad} | {bad / len(ks):.0%} | {lo:.0%}–{hi:.0%} |")
    rr = s["audit_random_rejects"]
    miss = sum(1 for k in rr if labels[k]["verdict"] == "relevant")
    lo, hi = stats.wilson(miss, len(rr))
    pop = s["population"]["rejected_after_heldout"]
    L += ["", f"**What 30 random rejects can say:** {miss} of {len(rr)} rejected postings were marked relevant by hand. "
          f"With 95% confidence the share of rejects Hemanth would want lies between {lo:.0%} and {hi:.0%}: "
          f"about {round(lo * pop)} to {round(hi * pop)} of the {pop} rejected postings outside the held-out set. "
          "This is an estimate from one sample of 30, not a measured rate for all postings.", ""]

    # 2. random rejects by the rule that rejected them
    by_rule = collections.Counter((base[k]["decided_by"], labels[k]["verdict"]) for k in rr)
    L += ["## 2. Random rejects by the rule that rejected them", "",
          "| rule | marked relevant (miss) | marked not relevant | can't tell |", "|---|---:|---:|---:|"]
    for rule in sorted({r for r, _ in by_rule}):
        L.append(f"| {rule} | {by_rule[(rule, 'relevant')]} | {by_rule[(rule, 'not relevant')]} | "
                 f"{by_rule[(rule, CANT_TELL)]} |")
    L.append("")

    # 3. measured changes
    L += ["## 3. Measured rule changes (on the 55 audit labels; in-sample)", "",
          "| version | what | correct / n | TP | FP | FN | TN | kept in corpus | flips vs v1.0 |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|"]
    rows_ = variants(current) + [("v1.1", vs["1.1"], "released Nov 22 (v1.0 + X1)"),
                                 ("v1.2", vs["1.2"], "released Nov 24 (v1.1 + R17, 5+ years rejected)")]
    for name, flt, what in rows_:
        res = base if name == "v1.0" else {k: score.score(p, flt) for k, p in c["postings"].items()}
        m = confusion(res, labels, audit_keys)
        kept = sum(1 for r in res.values() if r["decision"] == "kept")
        flips = sum(1 for k in res if res[k]["decision"] != base[k]["decision"])
        L.append(f"| {name} | {what} | {m['correct']} / {m['n']} | {m['TP']} | {m['FP']} | {m['FN']} | {m['TN']} | "
                 f"{kept} | {flips} |")
    L.append("")

    # 4. every audit posting
    v11 = {k: score.score(p, vs["1.1"]) for k, p in c["postings"].items()}
    v12 = {k: score.score(p, vs["1.2"]) for k, p in c["postings"].items()}
    L += ["## 4. Every audit posting", "",
          "| item | stratum | title | board | hand | v1.0 | rule | score | v1.1 | v1.2 | matched |",
          "|---:|---|---|---|---|---|---|---:|---|---|---|"]
    for name, _ in STRATA:
        for k in sorted(s[name], key=lambda k: labels[k]["item"]):
            r, r1, r2, lab = base[k], v11[k], v12[k], labels[k]
            flag = " **✗**" if wrong(r["decision"], lab["verdict"]) else ""
            matched = "; ".join(x for x in [
                "role: " + ", ".join(r["role_words"]) if r["role_words"] else "",
                "skills: " + ", ".join(r["skills"]) if r["skills"] else "",
                "seniority: " + ", ".join(r["seniority"]) if r["seniority"] else "",
                "excluded: " + ", ".join(r["excluded_by"]) if r["excluded_by"] else ""] if x)
            L.append(f"| {lab['item']} | {name.replace('audit_', '')} | {r['title']} | {r['board']} | {lab['verdict']} | "
                     f"{r['decision']}{flag} | {r['decided_by']} | {r['score']} | {r1['decision']} | {r2['decision']} | {matched} |")
    out = "\n".join(L) + "\n"
    if write:
        (ROOT / "audit" / ("audit-results-corrected.md" if label_set == "corrected" else "audit-results.md")).write_text(out)
    return out
