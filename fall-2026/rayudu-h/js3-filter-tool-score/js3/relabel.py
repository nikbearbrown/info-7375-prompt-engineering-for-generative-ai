"""The second labeling pass: every labeled posting whose text states a number of years (the first
view hid all of them) is shown again with view v2 (js3/labeling.py), blind, in a seeded order.

    python -m js3 relabel draw      # needs audit/relabel-seed.json (committed first)
    python -m js3 relabel report    # after the labels: first vs second verdicts -> audit/relabel-results.md
"""
from __future__ import annotations

import collections
import json
import random

from . import ROOT, corpus, labeling, stats

ITEM_OFFSET = 200


def first_labels() -> dict:
    out = {}
    for f in ("labels.csv", "x1-labels.csv"):
        for k, v in labeling.read_labels(ROOT / "audit" / f).items():
            out[k] = {**v, "file": f}
    return out


def draw() -> dict:
    seed = json.loads((ROOT / "audit" / "relabel-seed.json").read_text())["seed"]
    c = corpus.load()
    first = first_labels()
    keys = sorted(k for k in first if labeling.states_years(c["postings"][k]["text"]))
    rng = random.Random(seed)
    order = list(keys)
    rng.shuffle(order)
    items = []
    for i, k in enumerate(order):
        p = c["postings"][k]
        items.append({"item": ITEM_OFFSET + i + 1, "key": k, "company": labeling.company(p), "title": p["title"],
                      "location": p["location"] or "(no location)", "url": p["url"], **labeling.view_v2(p)})
    (ROOT / "audit" / "relabel-list.json").write_text(json.dumps(
        {"seed": seed, "rule": "every posting already labeled (audit/labels.csv, audit/x1-labels.csv) whose full text "
                               "states a number of years (labeling.states_years)",
         "n": len(order), "keys_in_order": order}, indent=2) + "\n")
    labeling.write_sheet_v2(items, ROOT / "audit" / "relabel-sheet.md")
    labeling.write_template(items, ROOT / "audit" / "labels-v2.csv")
    return {"n": len(order), "of_labeled": len(first)}


def corrected_labels() -> dict:
    """First-pass verdicts, replaced by the second-pass verdict wherever there is one."""
    first = first_labels()
    second = labeling.read_labels(ROOT / "audit" / "labels-v2.csv")
    return {k: (second[k] if k in second else v) for k, v in first.items()}


def report() -> str:
    first = first_labels()
    second = labeling.read_labels(ROOT / "audit" / "labels-v2.csv")
    pairs = collections.Counter((first[k]["verdict"], second[k]["verdict"]) for k in second)
    n = len(second)
    changed = sum(v for (a, b), v in pairs.items() if a != b)
    lo, hi = stats.wilson(changed, n)
    L = ["# Second labeling pass (generated by `python -m js3 relabel report`)", "",
         f"{n} postings shown again with view v2 (the experience sentences visible). Verdicts changed on "
         f"**{changed} of {n}** (Wilson 95% {lo:.0%}–{hi:.0%}).", "",
         "| first pass → second pass | postings |", "|---|---:|"]
    for (a, b), v in sorted(pairs.items()):
        L.append(f"| {a} → {b} | {v} |")
    c = corpus.load()
    L += ["", "| item | title | first | second | experience shown |", "|---:|---|---|---|---|"]
    for k in sorted(second, key=lambda k: second[k]["item"]):
        if first[k]["verdict"] != second[k]["verdict"]:
            ex = "; ".join(labeling.years_sentences(c["postings"][k]["text"]))[:160]
            L.append(f"| {second[k]['item']} | {c['postings'][k]['title']} | {first[k]['verdict']} | "
                     f"{second[k]['verdict']} | {ex} |")
    return "\n".join(L) + "\n"
