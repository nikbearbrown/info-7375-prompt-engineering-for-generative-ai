"""An out-of-sample test of X1, the one rule change accepted after the audit.

X1 ("Staff" inside "Technical Staff" is not seniority) was chosen on the 55 audit labels, and
none of the 40 held-out postings is affected by it. So: from the postings X1 changes that have
never been labeled, draw 10 at random, mix them blind with 10 random unaffected controls, and
have Hemanth label all 20. These labels were never used to choose or tune X1.

    python -m js3 x1test draw      # needs audit/x1-seed.json (committed first)
    python -m js3 x1test report    # after the labels: -> audit/x1-results.md
"""
from __future__ import annotations

import json
import random

from . import ROOT, audit, corpus, filterdoc, labeling, score, stats

ITEM_OFFSET = 95            # continue the numbering after the first 95 items


def affected_and_controls(c=None):
    c = c or corpus.load()
    v11 = filterdoc.load()
    v10 = audit.variants(v11)[0][1]
    s = json.loads((ROOT / "audit" / "samples.json").read_text())
    labeled = set(s["heldout"] + s["audit_random_rejects"] + s["audit_closest"] + s["audit_kept"])
    r10 = {k: score.score(p, v10) for k, p in c["postings"].items()}
    r11 = {k: score.score(p, v11) for k, p in c["postings"].items()}
    flipped = sorted(k for k in c["postings"] if r10[k]["decision"] != r11[k]["decision"])
    unlabeled_flipped = [k for k in flipped if k not in labeled]
    controls_pool = sorted(k for k in c["postings"] if k not in labeled and k not in flipped
                           and c["postings"][k]["board"] == "perplexity")
    return {"flipped": flipped, "unlabeled_flipped": unlabeled_flipped, "controls_pool": controls_pool,
            "r10": r10, "r11": r11, "labeled_before": sorted(set(flipped) & labeled)}


def draw() -> dict:
    seed = json.loads((ROOT / "audit" / "x1-seed.json").read_text())["seed"]
    c = corpus.load()
    a = affected_and_controls(c)
    rng = random.Random(seed)
    test = rng.sample(a["unlabeled_flipped"], 10)
    controls = rng.sample(a["controls_pool"], 10)
    out = {"seed": seed, "x1_test": test, "controls": controls,
           "population": {"flipped_by_x1": len(a["flipped"]), "already_labeled": a["labeled_before"],
                          "unlabeled_flipped": len(a["unlabeled_flipped"]), "controls_pool": len(a["controls_pool"])}}
    (ROOT / "audit" / "x1-samples.json").write_text(json.dumps(out, indent=2) + "\n")
    items = labeling.build(test + controls, c["postings"], seed=seed + 1)
    for it in items:
        it["item"] += ITEM_OFFSET
    labeling.write_sheet(items, ROOT / "audit" / "x1-labeling-sheet.md")
    labeling.write_template(items, ROOT / "audit" / "x1-labels.csv")
    return out


def report() -> str:
    s = json.loads((ROOT / "audit" / "x1-samples.json").read_text())
    labels = labeling.read_labels(ROOT / "audit" / "x1-labels.csv")
    a = affected_and_controls()
    L = ["# X1 out-of-sample test (generated by `python -m js3 x1test report`)", "",
         f"Seed {s['seed']} (`audit/x1-seed.json`, committed before the draw). X1 changes "
         f"{s['population']['flipped_by_x1']} postings; {len(s['population']['already_labeled'])} of them were already "
         f"in the audit (and suggested X1), {s['population']['unlabeled_flipped']} had never been labeled. "
         "10 were drawn from those, mixed blind with 10 unaffected Perplexity controls, and labeled by Hemanth.", "",
         "| set | n | Hemanth: relevant | v1.0 right (rejected) | v1.1 right (kept) |", "|---|---:|---:|---:|---:|"]
    test = [k for k in s["x1_test"] if k in labels]
    rel = sum(1 for k in test if labels[k]["verdict"] == "relevant")
    notrel = sum(1 for k in test if labels[k]["verdict"] == "not relevant")
    L.append(f"| X1-affected | {len(test)} | {rel} | {notrel} | {rel} |")
    ctl = [k for k in s["controls"] if k in labels]
    agree = sum(1 for k in ctl if (a["r11"][k]["decision"] == "kept") == (labels[k]["verdict"] == "relevant"))
    L.append(f"| controls (X1 changes nothing) | {len(ctl)} | "
             f"{sum(1 for k in ctl if labels[k]['verdict'] == 'relevant')} | {agree} | {agree} |")
    if test:
        lo, hi = stats.wilson(rel, len(test))
        L += ["", f"On the postings X1 changes, v1.1 was right {rel} of {len(test)} times (Wilson 95% "
                  f"{lo:.0%}–{hi:.0%}); v1.0 was right {notrel} of {len(test)}.", "",
              "| item | title | Hemanth | v1.0 | v1.1 |", "|---:|---|---|---|---|"]
        for k in sorted(test, key=lambda k: labels[k]["item"]):
            L.append(f"| {labels[k]['item']} | {a['r11'][k]['title']} | {labels[k]['verdict']} | "
                     f"{a['r10'][k]['decision']} ({a['r10'][k]['score']}) | {a['r11'][k]['decision']} ({a['r11'][k]['score']}) |")
    return "\n".join(L) + "\n"
