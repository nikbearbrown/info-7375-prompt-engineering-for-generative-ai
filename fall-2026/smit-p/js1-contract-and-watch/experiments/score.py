#!/usr/bin/env python3
"""score.py — recompute every number in SAMPLING-REPORT.md and PROMPT-EXPERIMENT.md from
the saved JSONL results and the hand labels. Writes experiments/results/SCORES.md.

    python3 experiments/score.py

Pass = the reply was ACCEPTED by the validator AND its verdict equals the hand label.
A REJECTED reply is a fail, whatever its verdict would have been.
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(ROOT, "src"))
import rule  # noqa: E402

RES = os.path.join(HERE, "results")


def jl(name):
    with open(os.path.join(RES, name + ".jsonl"), encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def main():
    sel = json.load(open(os.path.join(HERE, "selection.json")))
    labels = json.load(open(os.path.join(HERE, "labels.json")))
    hand = {int(k): v for part in ("dev", "held_out") for k, v in labels[part].items()}
    jobs = {j["id"]: j for j in json.load(open(os.path.join(ROOT, sel["raw_file"])))["jobs"]}
    resume = json.load(open(os.path.join(ROOT, "persona", "aarav-patel.resume.json")))
    out = ["# Scores (generated by experiments/score.py — do not edit by hand)", ""]

    # ---- sampling
    samp = jl("sampling-baseline")
    out += ["## Sampling — baseline prompt, 4 fresh calls per posting", "",
            "| posting | title | hand label | rule (record) | Claude verdicts r1–r4 | accepted | agree w/ each other | agree w/ hand label |",
            "|---|---|---|---|---|---|---|---|"]
    by = collections.defaultdict(list)
    for r in samp:
        by[r["posting_id"]].append(r)
    for pid in sel["sampling_5"]:
        rs = sorted(by[pid], key=lambda r: r["repeat"])
        vs = [r["verdict"] or "REJECTED" for r in rs]
        acc = [r["verdict"] for r in rs if r["status"] == "ACCEPTED"]
        top = collections.Counter(acc).most_common(1)[0] if acc else (None, 0)
        out.append(f"| {pid} | {jobs[pid]['title'].strip()} | {hand[pid]} | {rule.judge(jobs[pid], resume)['verdict']} | "
                   f"{', '.join(vs)} | {len(acc)}/{len(rs)} | {top[1]}/{len(acc)} | {sum(v == hand[pid] for v in acc)}/{len(rs)} |")
    out.append("")

    # ---- prompt experiment
    out += ["## Prompt experiment — pass = ACCEPTED and equal to hand label", "",
            "| set | prompt | n | accepted | rejected | pass | false relevant | false not-relevant |", "|---|---|---|---|---|---|---|---|"]
    for name, part in (("dev-baseline", "dev"), ("dev-revision", "dev"), ("heldout-baseline", "held_out"), ("heldout-revision", "held_out")):
        rs = jl(name)
        acc = [r for r in rs if r["status"] == "ACCEPTED"]
        p = sum(r["verdict"] == hand[r["posting_id"]] for r in acc)
        fr = sum(r["verdict"] == "relevant" and hand[r["posting_id"]] == "not_relevant" for r in acc)
        fn = sum(r["verdict"] == "not_relevant" and hand[r["posting_id"]] == "relevant" for r in acc)
        out.append(f"| {part} | {rs[0]['prompt']} | {len(rs)} | {len(acc)} | {len(rs) - len(acc)} | {p}/{len(rs)} | {fr} | {fn} |")
    out += ["", "### Every miss", "", "| set | prompt | posting | title | location | hand | Claude | why |", "|---|---|---|---|---|---|---|---|"]
    for name in ("dev-baseline", "dev-revision", "heldout-baseline", "heldout-revision"):
        for r in jl(name):
            pid = r["posting_id"]
            if r["status"] != "ACCEPTED" or r["verdict"] != hand[pid]:
                why = r.get("reject_reason") or r.get("reason", "")
                out.append(f"| {r['set']} | {r['prompt']} | {pid} | {jobs[pid]['title'].strip()} | {jobs[pid]['location']['name']} | "
                           f"{hand[pid]} | {r['verdict'] or r['status']} | {why.replace('|', '/')[:140]} |")

    # ---- the written rule against the hand labels (a record, for comparison)
    out += ["", "## The written rule (record) against the same hand labels", "", "| set | n | agree | disagreements |", "|---|---|---|---|"]
    for part in ("dev", "held_out"):
        ids = sel[part]
        dis = [pid for pid in ids if rule.judge(jobs[pid], resume)["verdict"] != hand[pid]]
        out.append(f"| {part} | {len(ids)} | {len(ids) - len(dis)}/{len(ids)} | {', '.join(map(str, dis)) or '—'} |")

    cost = sum((r.get("cost_usd") or 0) for n in ("sampling-baseline", "dev-baseline", "dev-revision", "heldout-baseline", "heldout-revision") for r in jl(n))
    out += ["", f"Total reported cost of these {sum(len(jl(n)) for n in ('sampling-baseline','dev-baseline','dev-revision','heldout-baseline','heldout-revision'))} calls: ${cost:.2f} (from the CLI's `total_cost_usd`).", ""]
    text = "\n".join(out)
    with open(os.path.join(RES, "SCORES.md"), "w", encoding="utf-8") as f:
        f.write(text)
    print(text)


if __name__ == "__main__":
    main()
