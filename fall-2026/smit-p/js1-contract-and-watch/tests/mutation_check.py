#!/usr/bin/env python3
"""mutation_check.py — break the code on purpose, one way at a time, and record whether the
test suite notices. A mutant that survives means the tests do not check that property.

    python3 tests/mutation_check.py          # writes tests/mutation-log.md

Each mutant is applied to a copy of src/ in a temporary directory; the real files are
never touched.
"""
import datetime as dt
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

MUTANTS = [
    # M1 is expected to survive: the later "needs a résumé field AND a posting field" check
    # rejects an empty justification too, so this guard is redundant (kept for a clearer message).
    ("M1", "validator ignores an empty justification (redundant guard)", "rule.py",
     "if not cites:", "if False:"),
    ("M2", "validator ignores a posting-id mismatch", "rule.py",
     'if verdict.get("posting_id") != posting.get("id"):', "if False:"),
    ("M3", "validator accepts invented quotes", "rule.py",
     "if not pt or find_whole(pt, fields[pf]) is None:", "if not pt:"),
    ("M4", "rule needs 1 skill instead of 2", "rule.py",
     "MIN_SKILLS = 2", "MIN_SKILLS = 1"),
    ("M5", "substring instead of whole-word matching", "rule.py",
     'r"(?<![A-Za-z0-9])" + re.escape(term) + r"(?![A-Za-z0-9])"', "re.escape(term)"),
    ("M6", "baseline reports every posting as new", "watch.py",
     "return [], True", "return list(jobs), True"),
    ("M7", "diff reports only the last posting", "watch.py",
     'return [j for j in jobs if j["id"] not in seen], False', "return jobs[-1:], False"),
    ("M8", "validator ignores which posting a verdict was made for", "rule.py",
     'if "posting_title" in verdict and verdict["posting_title"] != posting.get("title", ""):', "if False:"),
    ("M9", "seniority check dropped", "rule.py",
     'SENIORITY_WORDS = ("senior", "sr", "staff", "principal", "manager")', "SENIORITY_WORDS = ()"),
    ("M10", "unshipped skills counted", "rule.py",
     'EXCLUDED_SKILL_GROUPS = {"familiar_with_not_shipped"}', "EXCLUDED_SKILL_GROUPS = set()"),
    ("M11", "allow-list check disabled", "watch.py",
     "if urllib.parse.urlparse(url).scheme != \"https\" or host not in ALLOWED_HOSTS:", "if False:"),
    ("M12", "fictional-persona check disabled", "watch.py",
     'if not email.endswith("@example.com") or "555" not in phone:', "if False:"),
    ("M13", "Claude validator accepts code fences / prose", "claude_judge.py",
     "obj = json.loads(text.strip())",
     "obj = json.loads(text.strip().strip('`').removeprefix('json').strip())"),
]


COPY = ("src", "tests", "persona", "hand-check", "runs")


def copy_tree(tmp):
    for d in COPY:
        shutil.copytree(os.path.join(ROOT, d), os.path.join(tmp, d), ignore=shutil.ignore_patterns("__pycache__"))


def run_suite(root):
    p = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests"],
                       cwd=root, capture_output=True, text=True)
    return p.returncode == 0, (p.stderr.strip().splitlines() or ["?"])[-1]


def main():
    rows = []
    ok, last = run_suite(ROOT)
    if not ok:
        sys.exit(f"the unmutated suite fails ({last}); fix that first")
    # Sanity check: an UNMUTATED copy must pass, or every mutant would look "caught".
    # (A first version of this script forgot to copy hand-check/ and reported a false 13/13.)
    with tempfile.TemporaryDirectory() as tmp:
        copy_tree(tmp)
        ok, last = run_suite(tmp)
        if not ok:
            sys.exit(f"an unmutated copy fails ({last}); the copy is missing something")
    for mid, what, fname, old, new in MUTANTS:
        with tempfile.TemporaryDirectory() as tmp:
            copy_tree(tmp)
            path = os.path.join(tmp, "src", fname)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            if old not in text:
                rows.append((mid, what, "NOT APPLIED (code changed — update this mutant)", ""))
                continue
            with open(path, "w", encoding="utf-8") as f:
                f.write(text.replace(old, new, 1))
            passed, last = run_suite(tmp)
            rows.append((mid, what, "SURVIVED (tests did not notice)" if passed else "caught", last))
    caught = sum(r[2] == "caught" for r in rows)
    lines = ["# Mutation check", "",
             f"Generated by `tests/mutation_check.py` on {dt.datetime.now().astimezone().isoformat(timespec='seconds')}. "
             f"**{caught} of {len(rows)} deliberate bugs were caught by the test suite.**", "",
             "| id | deliberate bug | result | suite output |", "|---|---|---|---|"]
    lines += [f"| {m} | {w} | {r} | `{o}` |" for m, w, r, o in rows]
    with open(os.path.join(ROOT, "tests", "mutation-log.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
