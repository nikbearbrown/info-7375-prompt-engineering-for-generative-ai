#!/usr/bin/env python3
"""Break the code on purpose, one way at a time, and record whether the tests notice.

    python3 tests/mutation_check.py          # writes tests/mutation-log.md

Each mutant is applied to a copy in a temporary directory; the real files are never touched.
The script refuses to run unless an UNMUTATED copy passes first, so a copy that is missing a
file cannot make every mutant look "caught".
"""
import datetime as dt
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COPY = ("src", "tests", "persona", "runs", "audit")

MUTANTS = [
    ("W1", "wrong version 1: substring matching (no whole-word boundaries)", "filter.py",
     'return r"(?<![A-Za-z0-9])" + body + r"(?![A-Za-z0-9])"', "return body"),
    ("W2", "wrong version 2: location ignored (every location counts as US)", "filter.py",
     "    if us is False:\n", "    if False:\n"),
    ("M1", "seniority rule R2 removed", "filter.py",
     'SENIORITY_WORDS = ["senior", "sr", "staff", "principal", "lead", "manager", "director", "head"]',
     "SENIORITY_WORDS = []"),
    ("M2", "missing location answered instead of 'cannot tell'", "filter.py",
     "    if us is None:\n", "    if False:\n"),
    ("M3", "v1.1 back to the smallest years number", "filter.py",
     'V1_1 = {**V1_0, "version": "1.1", "years_bound": "largest",',
     'V1_1 = {**V1_0, "version": "1.1", "years_bound": "smallest",'),
    ("M4", "skill threshold off by one (v1.0 needs 3)", "filter.py",
     "MIN_SKILLS = 2", "MIN_SKILLS = 3"),
    ("M5", "unshipped skills counted", "filter.py",
     'EXCLUDED_SKILL_GROUPS = {"familiar_with_not_shipped"}', "EXCLUDED_SKILL_GROUPS = set()"),
    ("M6", "collector allow-list disabled", "collect.py",
     'if p.scheme != "https" or p.hostname not in ALLOWED_HOSTS:', "if False:"),
    ("M7", "tool server accepts any posting_id (no pattern check)", "mcp_server.py",
     "if not isinstance(pid, str) or not re.match(ID_PATTERN, pid):", "if not isinstance(pid, str):"),
    ("M8", "tool server accepts extra arguments", "mcp_server.py",
     'if not isinstance(args, dict) or set(args) - {"board", "posting_id"}:', "if not isinstance(args, dict):"),
    ("M9", "claim checker ignores hedges like e.g. / such as", "shortlist.py",
     "if HEDGE.search(sentence) or in_or_list(sentence, skill):", "if in_or_list(sentence, skill):"),
    ("M11", "tool server also writes a file outside its transcript", "mcp_server.py",
     "        self.transcript_path = transcript_path\n",
     "        self.transcript_path = transcript_path\n        open(os.path.join(ROOT, 'runs', 'leak.txt'), 'w').write('x')\n"),
    ("M10", "years phrase without a number no longer abstains", "filter.py",
     "        if not found and unnumbered is None and _YEARS_NO_NUMBER.search(sentence):",
     "        if False:"),
]


def copy_tree(tmp):
    for d in COPY:
        shutil.copytree(os.path.join(ROOT, d), os.path.join(tmp, d), ignore=shutil.ignore_patterns("__pycache__"))


def run_suite(root):
    p = subprocess.run([sys.executable, "-m", "unittest", "discover", "-s", "tests"],
                       cwd=root, capture_output=True, text=True)
    return p.returncode == 0, (p.stderr.strip().splitlines() or ["?"])[-1]


def main():
    ok, last = run_suite(ROOT)
    if not ok:
        sys.exit(f"the unmutated suite fails ({last}); fix that first")
    with tempfile.TemporaryDirectory() as tmp:
        copy_tree(tmp)
        ok, last = run_suite(tmp)
        if not ok:
            sys.exit(f"an unmutated copy fails ({last}); the copy is missing something")
    rows = []
    for mid, what, fname, old, new in MUTANTS:
        with tempfile.TemporaryDirectory() as tmp:
            copy_tree(tmp)
            path = os.path.join(tmp, "src", fname)
            with open(path, encoding="utf-8") as f:
                text = f.read()
            if old not in text:
                rows.append((mid, what, "NOT APPLIED (code changed; update this mutant)", ""))
                continue
            with open(path, "w", encoding="utf-8") as f:
                f.write(text.replace(old, new, 1))
            passed, last = run_suite(tmp)
            rows.append((mid, what, "SURVIVED (tests did not notice)" if passed else "caught", last))
    caught = sum(r[2] == "caught" for r in rows)
    lines = ["# Mutation check", "",
             f"Generated by `tests/mutation_check.py` on {dt.datetime.now().astimezone().isoformat(timespec='seconds')}. "
             f"**{caught} of {len(rows)} deliberate bugs were caught by the test suite.**", "",
             "| id | deliberate bug | result | suite output |", "|---|---|---|---|"]
    lines += [f"| {m} | {w} | {r} | `{o}` |" for m, w, r, o in rows]
    if any(m == "M7" and r.startswith("SURVIVED") for m, _, r, _ in rows):
        lines += ["", "**Why M7 survives.** With the id-pattern check removed, a path-like id such as "
                  "`../../persona/aarav-patel.resume` is still refused: the server looks ids up in an in-memory "
                  "table built from the saved run and never uses an id as a file path. The pattern check is a "
                  "second guard, so no test can tell it is gone. Kept and reported rather than hidden."]
    with open(os.path.join(ROOT, "tests", "mutation-log.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
