"""Draw 5 postings for the Sampling Report and write a BLANK hand-label
worksheet: id, title, and content text only. Computes no verdict of any kind.

Selection is a seeded random draw (not hand-picked) from the baseline
postings, excluding the 7 ids already used in the compare step.

    python3 scripts/make_sampling_worksheet.py
"""
import html
import json
import random
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "evidence" / "gitlab_jobs_20261030T201528Z.json"
OUT = ROOT / "logs" / "sampling_hand_labels_BLANK.md"
SEED = 20261030
N = 5
EXCLUDE = {9999999002, 8704363002, 8883003002, 8565469002,
           8621733002, 8738179002, 8646544002}


def readable(raw):
    """HTML-escaped Greenhouse content -> plain text, keeping paragraph and
    list breaks so a human can read it. Drops tags only, never words."""
    t = html.unescape(raw or "")
    t = re.sub(r"(?i)<li[^>]*>", "\n- ", t)
    t = re.sub(r"(?i)<br\s*/?>|</(p|div|h[1-6]|li|ul|ol)>", "\n", t)
    t = re.sub(r"<[^>]+>", "", t)
    t = html.unescape(t).replace("\xa0", " ")
    t = re.sub(r"[ \t]+", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    return re.sub(r"\n{3,}", "\n\n", t).strip()


def main():
    jobs = json.loads(BASELINE.read_bytes())["jobs"]
    pool = sorted((j for j in jobs if j["id"] not in EXCLUDE), key=lambda j: j["id"])
    picked = random.Random(SEED).sample(pool, N)

    lines = [
        "# Sampling Report: hand-label worksheet (BLANK)",
        "",
        f"Source: `{BASELINE.relative_to(ROOT)}` (real baseline response, 2026-10-30T20:15:28Z).",
        f"Selection: `random.Random({SEED}).sample(pool, {N})` over the {len(pool)} baseline postings",
        "sorted by id, excluding the 7 ids used in the compare step. Generated by",
        "`scripts/make_sampling_worksheet.py`. No rule or judgment verdict was computed",
        "for these postings before this worksheet was written.",
        "",
        "Content below is the posting's HTML with tags removed (text kept verbatim).",
        "",
        "Labeling rule used (write before labeling): ________________________________",
        "",
    ]
    for i, j in enumerate(picked, 1):
        lines += [
            "---",
            "",
            f"## {i}. id {j['id']}",
            "",
            f"**Title:** {j['title'].strip()}",
            "",
            "**Content:**",
            "",
            readable(j.get("content")),
            "",
            "**Hand label (relevant / not relevant):** ________",
            "",
            "**Reason (fields relied on):** ________",
            "",
        ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")
    for j in picked:
        print(f"  {j['id']}  {j['title'].strip()}  ({len(readable(j.get('content')))} chars)")


if __name__ == "__main__":
    main()
