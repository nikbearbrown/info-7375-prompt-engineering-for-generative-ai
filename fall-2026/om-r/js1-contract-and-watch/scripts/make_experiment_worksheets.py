"""Draw 20 fresh postings for the Prompt Experiment (Chapter 2) and write
BLANK hand-label worksheets: dev = first 10 in draw order, held-out = last
10. Id, title, and content text only. Computes no verdict of any kind.

Pool: the baseline postings minus the 7 compare-step ids and the 5
Sampling Report ids.

    python3 scripts/make_experiment_worksheets.py
"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from make_sampling_worksheet import BASELINE, readable  # noqa: E402

SEED = 20261031
N = 20
COMPARE_IDS = {9999999002, 8704363002, 8883003002, 8565469002,
               8621733002, 8738179002, 8646544002}
SAMPLING_IDS = {8860219002, 8716143002, 8860273002, 8783485002, 8918216002}
OUT = {"dev": ROOT / "logs" / "experiment_dev_BLANK.md",
       "heldout": ROOT / "logs" / "experiment_heldout_BLANK.md"}
IDS_FILE = ROOT / "logs" / "experiment_split.json"


def worksheet(name, title, picked, pool_size):
    lines = [
        f"# Prompt Experiment: {title} hand-label worksheet (BLANK)",
        "",
        f"Source: `{BASELINE.relative_to(ROOT)}` (real baseline response, 2026-10-30T20:15:28Z).",
        f"Selection: `random.Random({SEED}).sample(pool, {N})` over the {pool_size} baseline",
        "postings sorted by id, excluding the 7 compare-step ids and the 5 Sampling",
        "Report ids. Draw positions 1-10 are the DEV set; 11-20 are the HELD-OUT set.",
        f"This file is the **{name.upper()}** set. Generated by",
        "`scripts/make_experiment_worksheets.py`. No rule or judgment verdict was",
        "computed for these postings before this worksheet was written.",
        "",
        "Content below is the posting's HTML with tags removed (text kept verbatim).",
        "",
        "Labeled by: ________   Date/time labeled (UTC): ________",
        "",
        "Labeling rule used (write before labeling): ________________________________",
        "",
    ]
    for pos, j in picked:
        lines += [
            "---", "",
            f"## Draw #{pos}. id {j['id']}", "",
            f"**Title:** {j['title'].strip()}", "",
            "**Content:**", "",
            readable(j.get("content")), "",
            "**Hand label (relevant / not relevant):** ________", "",
            "**Reason (fields relied on):** ________", "",
        ]
    OUT[name].write_text("\n".join(lines))


def main():
    jobs = json.loads(BASELINE.read_bytes())["jobs"]
    excluded = COMPARE_IDS | SAMPLING_IDS
    pool = sorted((j for j in jobs if j["id"] not in excluded), key=lambda j: j["id"])
    drawn = list(enumerate(random.Random(SEED).sample(pool, N), 1))
    dev, heldout = drawn[:10], drawn[10:]
    assert not {j["id"] for _, j in drawn} & excluded

    worksheet("dev", "DEVELOPMENT set", dev, len(pool))
    worksheet("heldout", "HELD-OUT set", heldout, len(pool))
    IDS_FILE.write_text(json.dumps({
        "seed": SEED, "pool_size": len(pool),
        "dev": [j["id"] for _, j in dev],
        "heldout": [j["id"] for _, j in heldout],
    }, indent=2) + "\n")

    print(f"pool: {len(pool)} postings")
    for name, part in (("DEV", dev), ("HELD-OUT", heldout)):
        print(f"\n{name}:")
        for pos, j in part:
            print(f"  #{pos:>2}  {j['id']}  {j['title'].strip()}")
    print(f"\nwrote {', '.join(str(p.relative_to(ROOT)) for p in OUT.values())}, "
          f"{IDS_FILE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
