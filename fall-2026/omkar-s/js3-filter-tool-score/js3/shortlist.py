"""The source-grounded shortlist (Chapter 7): every claim in every justification, labelled against the posting.

    python3 -m js3.shortlist [--run <corpus run>]

Writes shortlist/shortlist-v<version>.md (the shortlist) and shortlist/claims-v<version>.csv (one row per
claim, with a blank `omkar_check` column for hand checks). Labels come from FILTER.md section 2 only.
"""
import argparse
import csv
import io
import os
import sys

from . import data, run_filter, scorer, store


def build(run_id=None):
    run_id, corpus = data.load_corpus(run_id)
    src = data.load_sources(run_id)
    cfg = scorer.load_filter()
    persona = data.load_persona()
    items = []
    for p in corpus:
        r = scorer.evaluate(p, persona, cfg)
        if r["verdict"] != "keep":
            continue
        cl = scorer.claims(p, r, cfg)
        st, why = scorer.shortlist_status(cl, cfg)
        items.append((r, cl, st, why))
    items.sort(key=lambda x: (x[2] != "worth_reading", -x[0]["score"], x[0]["title"]))
    v = cfg["version"]
    L = [f"# Shortlist (filter v{v}, corpus {run_id})", "",
         "Generated by `python3 -m js3.shortlist`. Each claim is labelled against the posting's own text by the rules in "
         "FILTER.md section 2 (**supported** / **contradicted** / **insufficient**), with the quote it rests on. "
         "Insufficient means the agent says **I cannot tell**.", "",
         run_filter.coverage_line(src), ""]
    groups = [("worth_reading", "Worth reading (role, location and level supported; at least 2 skills asked for)"),
              ("kept_cannot_tell", "Kept, but I cannot tell (the reason is given for each)")]
    rows = []
    for key, title in groups:
        g = [x for x in items if x[2] == key]
        L += [f"## {title}: {len(g)}", ""]
        for r, cl, st, why in g:
            L += [f"### {r['company']} · {r['title']} (score {r['score']})", "",
                  f"`{r['source']}` id {r['id']} · {r['location']} · {r['url'] or '(no link)'}", "",
                  "Score lines (they sum to the score): " + "; ".join(f"{l['rule']} {l['points']:+g} ({l['why']})" for l in r["lines"]), ""]
            if why:
                L += ["**Why I cannot tell:** " + " · ".join(why), ""]
            L += ["| Claim | Label | Field | Quote from the posting | Note |", "|---|---|---|---|---|"]
            for c in cl:
                q = (c["quote"] or "—").replace("|", "/").replace("\n", " ")
                L.append(f"| {c['text']} | **{c['label']}** | {c['field']} | {q[:240]} | {c['note'].replace('|', '/')} |")
                rows.append({"source": r["source"], "id": r["id"], "title": r["title"], "claim": c["claim"],
                             "label": c["label"], "quote": c["quote"], "note": c["note"], "omkar_check": ""})
            L.append("")
    counts = {}
    for row in rows:
        counts[row["label"]] = counts.get(row["label"], 0) + 1
    L += ["## Claim totals", "", ", ".join(f"{k}: {n}" for k, n in sorted(counts.items())) + f" (of {len(rows)} claims on {len(items)} postings)", ""]
    store.write_text(f"shortlist/shortlist-v{v}.md", "\n".join(L))
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0]) if rows else ["source"])
    w.writeheader()
    w.writerows(rows)
    path = f"shortlist/claims-v{v}.csv"
    if os.path.exists(os.path.join(store.BASE, path)):
        with open(os.path.join(store.BASE, path), encoding="utf-8") as f:
            if any(r.get("omkar_check") for r in csv.DictReader(f)):
                print(f"{path} has hand checks; not overwritten")
                return items
    store.write_text(path, buf.getvalue())
    return items


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run")
    a = ap.parse_args(argv)
    items = build(a.run)
    n = sum(1 for x in items if x[2] == "worth_reading")
    print(f"shortlist: {len(items)} kept → {n} worth reading, {len(items) - n} kept but I cannot tell")
    return 0


if __name__ == "__main__":
    sys.exit(main())
