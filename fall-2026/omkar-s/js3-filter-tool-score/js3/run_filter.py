"""Run one filter version over everything the agent collected, and measure every rule.

    python3 -m js3.run_filter [--run <corpus run>] [--filter filter/filter-v1.0.json]

Writes runs/<corpus run>/filter-v<version>/records.jsonl.gz and summary.md. summary.md is the
measurement behind every FILTER.md change-log row: how often each rule fired, on what kinds of
title, and which postings each candidate change would flip.
"""
import argparse
import collections
import gzip
import json
import os
import sys

from . import data, scorer, store
from . import textutil as tu


def run(run_id=None, filter_path=scorer.DEFAULT_FILTER):
    run_id, corpus = data.load_corpus(run_id)
    src = data.load_sources(run_id)
    cfg = scorer.load_filter(filter_path)
    persona = data.load_persona()
    recs = [scorer.evaluate(p, persona, cfg) for p in corpus]
    for p, r in zip(corpus, recs):
        if r["verdict"] == "keep":
            cl = scorer.claims(p, r, cfg)
            r["claims"] = cl
            r["shortlist_status"], r["shortlist_reasons"] = scorer.shortlist_status(cl, cfg)
    out = f"runs/{run_id}/filter-v{cfg['version']}"
    body = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in recs).encode("utf-8")
    store.write_bytes(f"{out}/records.jsonl.gz", gzip.compress(body, mtime=0))
    store.write_text(f"{out}/summary.md", summary(run_id, src, cfg, corpus, recs))
    return run_id, cfg, corpus, recs


def coverage_line(src):
    ok = [s for s in src["sources"] if s["status"] == "ok"]
    parts = [f"`{s['source']}` {s['status']} ({s['postings']})" for s in src["sources"]]
    line = f"covered {len(ok)} of {len(src['sources'])} sources: " + ", ".join(parts)
    missing = [s for s in src["sources"] if s["status"] != "ok"]
    if missing:
        line += ". **INCOMPLETE.** " + " ".join(
            f"I cannot tell whether {s['company']} (`{s['source']}`) has matching postings ({s['reason'] or s['status']})."
            for s in missing)
    return line


def _is_eng(r, cfg):
    return bool(r["role_phrase"] or (tu.has_any(r["title"], cfg["engineer_words"]) and not r["non_software"]))


def summary(run_id, src, cfg, corpus, recs):
    v = collections.Counter(r["verdict"] for r in recs)
    L = [f"# Filter v{cfg['version']} on corpus {run_id}", "",
         "Generated by `python3 -m js3.run_filter`. Every number below is a count over the whole corpus, not a sample.", "",
         coverage_line(src), "",
         f"**{len(recs)} postings → keep {v['keep']} · reject {v['reject']} · cannot_tell {v['cannot_tell']}** "
         f"(close calls: {sum(r['close_call'] for r in recs)})", "",
         "| Source | Postings | Keep | Reject | Cannot tell |", "|---|---:|---:|---:|---:|"]
    by = collections.defaultdict(collections.Counter)
    for r in recs:
        by[r["source"]][r["verdict"]] += 1
    for s in src["sources"]:
        c = by.get(s["source"], collections.Counter())
        L.append(f"| `{s['source']}` | {s['postings']} | {c['keep']} | {c['reject']} | {c['cannot_tell']} |")
    L += ["", "## How often each rule fired", "", "| Rule | Fired on | of which kept |", "|---|---:|---:|"]
    fired = collections.Counter()
    kept = collections.Counter()
    for r in recs:
        for rule in {l["rule"] for l in r["lines"]}:
            fired[rule] += 1
            kept[rule] += r["verdict"] == "keep"
        for g in ("G1", "G2", "G3"):
            if not r["gates"][g]["pass"]:
                fired[g + " failed"] += 1
    for k in sorted(fired):
        L.append(f"| {k} | {fired[k]} | {kept[k] if not k.endswith('failed') else '—'} |")
    L += ["", "## Skill words by kind of title (false-friend check)", "",
          "A skill word that fires mostly on non-engineering titles is a candidate false friend: it matched, but not because the job is a software job.", "",
          "| Skill | Engineering titles | Other titles | Top source on other titles |", "|---|---:|---:|---|"]
    hits = collections.defaultdict(lambda: [0, 0, collections.Counter()])
    for r in recs:
        for s in r["skills_found"]:
            h = hits[s]
            if _is_eng(r, cfg):
                h[0] += 1
            else:
                h[1] += 1
                h[2][r["source"]] += 1
    for s, (e, o, c) in sorted(hits.items(), key=lambda x: -x[1][1]):
        top = ", ".join(f"{k} {n}" for k, n in c.most_common(2)) or "—"
        L.append(f"| {s} | {e} | {o} | {top} |")
    L += ["", "## Generic-engineer titles (rule T2) and seniority words (T3)", ""]
    t2 = collections.Counter(r["title"] for r in recs if any(l["rule"] == "T2" for l in r["lines"]))
    L.append(f"T2 fired on {sum(t2.values())} postings, {len(t2)} distinct titles: " +
             "; ".join(f"{t} ({n})" for t, n in t2.most_common()))
    t3 = collections.Counter(r["seniority"] for r in recs if r["seniority"])
    L.append("")
    L.append("T3 words: " + ", ".join(f"`{k}` {n}" for k, n in t3.most_common()) +
             ". Non-engineering titles with `lead`: " +
             "; ".join(sorted({r["title"] for r in recs if r["seniority"] == "lead" and not _is_eng(r, cfg)})[:12]))
    L += ["", "## Entry phrases (rule Y1) in context", ""]
    for p, r in zip(corpus, recs):
        if r["entry_phrase"]:
            t = tu.clean(p.get("content"))
            m = tu.ww(r["entry_phrase"]).search(t)
            ctx = t[max(0, m.start() - 80):m.end() + 60] if m else "(in title)"
            L.append(f"- {r['company']} · {r['title']} · `{r['entry_phrase']}` · verdict {r['verdict']}: …{ctx}…")
    L += ["", "## Years statements (G3) on titles with a T1 role phrase", ""]
    yd = collections.Counter(r["gates"]["G3"]["min_years"] for r in recs if r["role_phrase"])
    L.append(", ".join(f"{'none' if k is None else k}: {n}" for k, n in sorted(yd.items(), key=lambda x: (x[0] is None, x[0] or 0))))
    L += ["", "## G1 failures on titles with a T1 role phrase (locations)", ""]
    g1 = collections.Counter(r["location"] for r in recs if r["role_phrase"] and not r["gates"]["G1"]["pass"])
    L.append("; ".join(f"{k or '(empty)'} ({n})" for k, n in g1.most_common()))
    L.append("")
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run")
    ap.add_argument("--filter", default=scorer.DEFAULT_FILTER)
    a = ap.parse_args(argv)
    run_id, cfg, corpus, recs = run(a.run, a.filter)
    v = collections.Counter(r["verdict"] for r in recs)
    print(f"filter v{cfg['version']} on {run_id}: {len(recs)} postings → keep {v['keep']}, "
          f"reject {v['reject']}, cannot_tell {v['cannot_tell']}; close calls {sum(r['close_call'] for r in recs)}")
    print(f"wrote runs/{run_id}/filter-v{cfg['version']}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
