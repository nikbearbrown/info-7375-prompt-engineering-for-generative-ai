"""Generate reports/boundary-tests.md by running the 19 boundary cases.

The predictions come from `tests/boundary_cases.py`, which is the same file
`tests/test_policy_boundaries.py` reads, and which transcribes what GATE.md §5.5
committed before any of this was run. The "actual" column is produced by calling
the real `agent.policy.Policy` here, now — it is not copied from a test run and
not typed by hand.

    python3 tools/boundary_table.py              # write the report
    python3 tools/boundary_table.py --check      # exit 1 if any row disagrees

No network is involved: every network refusal is decided on the URL string
before a socket is opened.
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent import errors  # noqa: E402
from agent.policy import Policy  # noqa: E402
from tests.boundary_cases import CASES  # noqa: E402

OUT = ROOT / "reports" / "boundary-tests.md"

KIND_LABEL = {"net": "request", "write": "write", "read": "read"}


def scratch_project(tmp: Path) -> Path:
    """A throwaway tree with the real project's shape, including the evil sibling."""
    (tmp / "config").mkdir()
    (tmp / "data").mkdir()
    (tmp / "evidence" / "raw").mkdir(parents=True)
    (tmp / "evidence" / "runs").mkdir(parents=True)
    (tmp / "evidence" / "state").mkdir(parents=True)
    (tmp / "evidence-evil").mkdir()
    shutil.copy(ROOT / "data" / "resume.persona.json", tmp / "data" / "resume.persona.json")
    return tmp


def run_case(project: Path, case: dict) -> str:
    if case.get("needs") == "symlink":
        link = project / "evidence" / "link"
        if not link.exists():
            link.symlink_to(project.parent, target_is_directory=True)
    if case.get("needs") == "existing":
        (project / "evidence" / "raw" / "already-there.json").write_text("{}", encoding="utf-8")

    policy = Policy(
        project_root=project,
        output_root=(project / "evidence").resolve(),
        approve_overwrite=bool(case.get("approve")),
    )
    try:
        if case["kind"] == "net":
            policy.check_request(case["method"], case["url"])
        else:
            path = case["path"]
            target = (
                project / "evidence" / path if path.startswith("..") else project / path
            )
            if case["kind"] == "write":
                policy.check_write(target)
            else:
                policy.check_read(target)
        return "allow"
    except errors.PolicyRefusal as exc:
        return f"deny:{type(exc).__name__}"


def subject(case: dict) -> str:
    if case["kind"] == "net":
        return f"`{case['method']} {case['url']}`"
    return f"`{case['path']}`"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument(
        "--check", action="store_true", help="only verify; do not write the report"
    )
    args = ap.parse_args(argv)

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        project = scratch_project(Path(tmp))
        for case in CASES:
            actual = run_case(project, case)
            rows.append((case, actual, actual == case["predicted"]))

    disagreements = [(c["n"], c["predicted"], a) for c, a, ok in rows if not ok]

    if args.check:
        for n, predicted, actual in disagreements:
            print(f"case {n}: predicted {predicted}, got {actual}")
        if disagreements:
            print(f"{len(disagreements)} of {len(rows)} cases disagree with GATE.md §5.5")
            return 1
        print(f"all {len(rows)} boundary cases match the predictions in GATE.md §5.5")
        return 0

    lines = [
        "# Boundary tests — permission policy P-v1",
        "",
        "**Generated by** `python3 tools/boundary_table.py`. Do not edit by hand.",
        "",
        "The **predicted** column is read from `tests/boundary_cases.py`, which",
        "transcribes the 19 cases written into `GATE.md` §5.5 **before any of this",
        "code existed**. The **actual** column is produced by calling the real",
        "`agent.policy.Policy` while this file is generated. Neither column is",
        "typed by hand, so the two cannot quietly drift into agreement.",
        "",
        "No network is involved. Every network refusal is decided on the URL",
        "string before a socket is opened, which is the reason the check lives in",
        "the policy and not in the HTTP layer.",
        "",
        f"**{sum(1 for _, _, ok in rows if ok)} of {len(rows)} cases matched the prediction.**",
        "",
        "| # | kind | subject | what it tests | predicted | actual | |",
        "|---|---|---|---|---|---|---|",
    ]
    for case, actual, ok in rows:
        mark = "ok" if ok else "**MISMATCH**"
        lines.append(
            f"| {case['n']} | {KIND_LABEL[case['kind']]} | {subject(case)} | "
            f"{case['desc']} | `{case['predicted']}` | `{actual}` | {mark} |"
        )

    lines += [
        "",
        "## Notes on the cases that matter most",
        "",
        "**Cases 5 and 12 are the two I most expected to get wrong, and they are",
        "in the table for that reason.** Case 5 is",
        "`boards-api.greenhouse.io.evil.example` — an allow-list checked with",
        "`endswith` would let it through, so `agent/policy.py` compares the parsed",
        "hostname for exact equality against a set. Case 12 is `evidence-evil/`, a",
        "sibling directory whose name begins with the output root's name — a",
        "confinement check written with `str.startswith` would allow a write there,",
        "so the check resolves both paths and asks whether the root is among the",
        "candidate's parents.",
        "",
        "**Case 13 is why that check resolves symlinks.** A symlink placed *inside*",
        "the output root pointing outside it defeats any check that reasons about",
        "the path as text. `Path.resolve()` follows it, and the parent-chain test",
        "then sees the real destination.",
        "",
        "**Case 14, the output root itself, is denied on purpose.** `evidence` is",
        "not a file to be written; treating it as one is how a directory gets",
        "replaced. The confinement helper returns `False` when the candidate *is*",
        "the root rather than a descendant of it.",
        "",
        "**Cases 15 to 17 exist because reading and writing are separate",
        "permissions.** A policy with one `check_path` would have to choose a",
        "single answer for `data/`, which the agent must read and must never",
        "write.",
        "",
        "**Case 16 is carried over from JS1's refusal R2.** `*.real.json` is",
        "unreadable by the agent, so the real résumé cannot be read even by",
        "accident, even inside the project.",
        "",
        "**Cases 18 and 19 are the same write, differing only in approval.** They",
        "are a pair so that the approval demonstrably *adds* a permission rather",
        "than being decorative; `test_approval_only_ever_adds_the_overwrite_"
        "permission` then checks it adds nothing else, by confirming that an",
        "approving policy still refuses a disallowed host, a disallowed method and",
        "an escaping path.",
        "",
        "## What this table does not establish",
        "",
        "- These are the cases I thought of. A boundary nobody predicted is not",
        "  in the table, and the table's own completeness is not evidence of the",
        "  policy's.",
        "- **The table checks the policy's *decisions*, not its call sites.** That",
        "  distinction is not academic: when this report was first generated, three",
        "  of the four files the agent writes — the run report, the state file and",
        "  the trace — did not go through `check_write` at all, and all 19 cases",
        "  below passed anyway, because each one calls the policy directly. The gap",
        "  was found by quoting GATE.md §5's \"there is no second path\" into this",
        "  file and then checking it; it is closed (amendment A3,",
        "  `tests/test_all_writes_go_through_the_policy.py`), and those tests are",
        "  deliberately **not** added to the 19, which are the predictions frozen",
        "  before any code existed. A table that passes completely is not evidence",
        "  that the thing it tests is the thing that matters.",
        "- Case 2 is allowed and 404s in real life. The policy decides on host,",
        "  scheme, port and method, and never on whether a board exists; a refusal",
        "  and a missing board are different outcomes and are reported differently.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} cases, {len(disagreements)} mismatch(es)")
    return 1 if disagreements else 0


if __name__ == "__main__":
    raise SystemExit(main())
