"""port_engine.py - derive the Remotion scene engine from the walkthrough's drawing code.

Reads ../early-bird-walkthrough/film.src.html, keeps the drawing code (CM, helpers, scenes, logo, icons),
drops the browser player, the synthesized sound kit and the score (the toolkit mixes sound), and rewrites the
timeline so it is built from a timeline object passed in as props (init(timeline)).
Writes <toolkit>/runtime/remotion/src/ebw/engine.ts
"""
import json, re, glob, os
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "early-bird-walkthrough"
TK = Path("C:/NEU course/PEAI/brutalist.art/runtime/remotion/src/ebw")
TK.mkdir(parents=True, exist_ok=True)

html = (SRC / "film.src.html").read_text(encoding="utf-8")
S = html[html.index("<script>") + len("<script>"): html.rindex("</script>")]

def cut(s, a_marker, b_marker, keep_b=True):
    a = s.index(a_marker)
    b = s.index(b_marker, a)
    return s[:a] + s[b:]

BAR = "// =====================================================================================================\n"
# 1. drop the sound kit
S = cut(S, BAR + "// SFX:", "// ---------- shared UI-style helpers")
# 2. drop padBed (sound helper)
S = cut(S, "// a soft synth pad and light percussion", BAR + "// STYLE: Software Walkthrough")
# 3. drop the score and the player
S = S[: S.index("// =================================== SOUND SCORE")]
# 4. timeline comes from props, not from CUES
a = S.index("// ---------- narration clock ----------")
b = S.index("const END = T.O03 + DUR.O03 + 1.6;") + len("const END = T.O03 + DUR.O03 + 1.6;")
S = S[:a] + "// ---------- narration clock (from props) ----------\nlet T = {}, DUR = {}, END = 0;\nconst at = (id, o = 0) => T[id] + o;" + S[b:]
# 5. wrap TL / CAM / CURSOR / NAV so they are built by init(timeline)
a = S.index("const TL = {")
b = S.index("const NAV = TL.nav;") + len("const NAV = TL.nav;")
seg = S[a:b]
step = re.search(r"const STEP_NAMES = \[.*?\];\n", seg, re.S).group(0)
seg = seg.replace(step, "")
seg = seg.replace("const TL = {", "TL = {", 1).replace("const CAM = [", "CAM = [", 1).replace("const CURSOR = [", "CURSOR = [", 1).replace("const NAV = TL.nav;", "NAV = TL.nav;", 1)
S = S[:a] + step + "let TL, CAM, CURSOR, NAV;\nexport function init(tl) {\n  T = tl.T; DUR = tl.DUR; END = tl.END;\n" + seg + "\n}\n" + S[b:]
# 6. draw at any scale
S = S.replace("function explainer(ctx, t) {\n  ctx.setTransform(1, 0, 0, 1, 0, 0);", "export let SC = 1;\nexport function setScale(v) { SC = v; }\nexport function explainer(ctx, t) {\n  ctx.setTransform(SC, 0, 0, SC, 0, 0);", 1)
assert "setTransform(SC" in S
# 7. icons embedded
icons = {os.path.splitext(os.path.basename(f))[0]: re.sub(r"<!--.*?-->\s*", "", open(f, encoding="utf-8").read(), flags=re.S).strip() for f in glob.glob(str(SRC / "icons" / "*.svg"))}
S = re.sub(r"/\*ICONS\*/.*?/\*ICONEND\*/", lambda m: "/*ICONS*/" + json.dumps(icons) + "/*ICONEND*/", S, flags=re.S)
S = S.replace("function loadIcons()", "export function loadIcons()", 1)
out = "// @ts-nocheck\n// Generated by port_engine.py from the Early Bird walkthrough drawing code. Do not edit by hand.\n" + S + "\n"
(TK / "engine.ts").write_text(out, encoding="utf-8")
print("wrote", TK / "engine.ts", len(out), "bytes")
