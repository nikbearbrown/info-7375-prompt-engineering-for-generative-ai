"""Compare my hand verdicts (labels/hand_verdicts.jsonl) with the filter and with the Claude runs.
Audit groups A/B/C and held-out H come from audit/sets.json (seeded draw, committed before judging).
Every interval is a Wilson 95% interval on THIS sample; scaled numbers are estimates, not measured rates.
Run:  python3 -m js3.report   -> out/report.md, out/report.json"""
import glob, json, math
from pathlib import Path
from js3 import filter as F, evidence as E

def wilson(k, n, z=1.96):
    if n == 0: return (None, None)
    p = k / n; d = 1 + z * z / n; c = p + z * z / (2 * n); h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (max(0.0, (c - h) / d), min(1.0, (c + h) / d))

def pct(x): return "–" if x is None else f"{100 * x:.1f}%"

def main(corrected=False):
    sets = json.loads(Path("audit/sets.json").read_text())
    hv = {}
    for l in Path("labels/hand_verdicts.jsonl").read_text().splitlines():
        r = json.loads(l); hv[r["id"]] = r
    tag = "original"
    if corrected:
        tag = "corrected"
        for l in Path("labels/hand_corrections.jsonl").read_text().splitlines():
            r = json.loads(l); hv[r["id"]] = dict(r, reason=r["reason"] + " [re-judged]")
    corpus = {p["id"]: p for p in F.load_corpus()}
    dec = {v: {json.loads(l)["id"]: json.loads(l) for l in open(f"out/decisions_v{v}.jsonl")} for v in ("1.0", "1.1", "1.2")}
    cfg10 = F.load_filter("filters/filter_v1.0.json")
    rep, md = {"n_judged": len(hv)}, [f"# Report: {tag} verdicts (generated by `python3 -m js3.report`)\n\nHand verdicts: **{len(hv)} of 76**"
                                          + (" with my 5 re-judged items from labels/hand_corrections.jsonl applied" if corrected else " exactly as frozen in labels/hand_verdicts.jsonl") + ".\n"]
    n_rej = sum(1 for d in dec["1.0"].values() if d["status"] == "rejected")

    # ---------- audit ----------
    md.append("## Audit (filter v1.0)\n| Group | Judged | ? | Filter wrong | Rate on this sample | Wilson 95% |\n|---|---|---|---|---|---|")
    rows = []
    for g, wrong_if in [("A_random_rejects", "y"), ("B_close_calls", "y"), ("C_kept_sample", "n")]:
        ids = [i for i in sets[g] if i in hv]; q = sum(hv[i]["verdict"] == "?" for i in ids)
        n = len(ids) - q; k = sum(hv[i]["verdict"] == wrong_if for i in ids); lo, hi = wilson(k, n)
        rep[g] = {"judged": len(ids), "unsure": q, "n": n, "wrong": k, "wilson": [lo, hi]}
        md.append(f"| {g} | {len(ids)} | {q} | {k} | {pct(k / n if n else None)} | {pct(lo)} – {pct(hi)} |")
        for i in ids:
            d = dec["1.0"][i]
            rows.append(f"| {g[0]} | `{i}` | {d['title'][:60]} | {d['status']} ({d['score']}; failed {','.join(d['failed']) or '-'}) | **{hv[i]['verdict']}** | {hv[i]['reason'] or ''} | {'**FILTER WRONG**' if hv[i]['verdict'] == wrong_if else ''} |")
    a = rep["A_random_rejects"]
    if a["n"]:
        lo, hi = a["wilson"]
        md.append(f"\nScaled to all {n_rej} v1.0 rejects, **if** this random sample is representative: about {round(lo * n_rej)}–{round(hi * n_rej)} "
                  f"wrongly rejected postings (an estimate from {a['n']} postings, not a measured count).\n")
        rep["scaled_rejects"] = [round(lo * n_rej), round(hi * n_rej), n_rej]
    md.append("### Every audited posting (my verdict vs the filter)\n| Grp | id | title | filter v1.0 | me | my reason | |\n|---|---|---|---|---|---|---|")
    md += sorted(rows)

    # ---------- held-out ----------
    H = [i for i in sets["H_heldout"] if i in hv and hv[i]["verdict"] != "?"]
    unsure = [i for i in sets["H_heldout"] if i in hv and hv[i]["verdict"] == "?"]
    truth = {i: hv[i]["verdict"] == "y" for i in H}
    scorers = {"always 'not relevant' (baseline)": {i: False for i in H},
               "filter v1.0": {i: dec["1.0"][i]["status"] == "kept" for i in H},
               "filter v1.1": {i: dec["1.1"][i]["status"] == "kept" for i in H},
               "filter v1.2": {i: dec["1.2"][i]["status"] == "kept" for i in H},
               "shortlist v1.0 (filter + evidence gate)": {i: E.justify(corpus[i], cfg10)["shortlist"] for i in H}}
    exps = json.loads(Path("runs/experiments.json").read_text())
    for x in [k for k in exps if not k.startswith("_")]:
        v = {}
        for f in glob.glob(f"runs/{x}/*.json"):
            r = json.loads(Path(f).read_text())
            if r["id"] in truth: v[r["id"]] = r["verdict"] == "relevant"
        scorers[f"Claude {x}: {exps[x]['what']}"] = v
    md.append(f"\n## Held-out (H): {len(H)} labelled y/n ({sum(truth.values())} y), {len(unsure)} '?' left out\n"
              "| Scorer | n | TP | FP | FN | TN | Accuracy | Wilson 95% | Precision | Recall |\n|---|---|---|---|---|---|---|---|---|---|")
    rep["heldout"] = {}
    for name, pred in scorers.items():
        ids = [i for i in H if i in pred]
        tp = sum(pred[i] and truth[i] for i in ids); fp = sum(pred[i] and not truth[i] for i in ids)
        fn = sum(not pred[i] and truth[i] for i in ids); tn = len(ids) - tp - fp - fn
        acc = (tp + tn) / len(ids) if ids else None; lo, hi = wilson(tp + tn, len(ids))
        prec = tp / (tp + fp) if tp + fp else None; rec = tp / (tp + fn) if tp + fn else None
        rep["heldout"][name] = dict(n=len(ids), tp=tp, fp=fp, fn=fn, tn=tn, acc=acc, wilson=[lo, hi], precision=prec, recall=rec)
        md.append(f"| {name} | {len(ids)} | {tp} | {fp} | {fn} | {tn} | {pct(acc)} | {pct(lo)} – {pct(hi)} | {pct(prec)} | {pct(rec)} |")
    b = {json.loads(Path(f).read_text())["id"]: json.loads(Path(f).read_text())["verdict"] for f in glob.glob("runs/B/*.json")}
    b2 = {json.loads(Path(f).read_text())["id"]: json.loads(Path(f).read_text())["verdict"] for f in glob.glob("runs/B2/*.json")}
    flips = [i for i in b if b[i] != b2.get(i)]
    rep["noise_floor_B_vs_B2_flips"] = flips
    md.append(f"\nNoise floor: the exact repeat B2 disagreed with B on **{len(flips)} of {len(b)}** held-out postings.\n")
    md.append("### Held-out items where any scorer disagrees with me\n| id | title | me | v1.0 | v1.1 | v1.2 | B | E1 | E2 | E3 | E4 |\n|---|---|---|---|---|---|---|---|---|---|---|")
    keys = list(scorers)
    for i in H:
        vals = [scorers[k].get(i) for k in keys[1:]]
        if any(v is not None and v != truth[i] for v in vals):
            yn = lambda v: "–" if v is None else ("y" if v else "n")
            cl = [scorers[k].get(i) for k in keys if k.startswith("Claude ") and not k.startswith("Claude B2")]
            md.append(f"| `{i}` | {corpus[i]['title'][:55]} | **{hv[i]['verdict']}** | {yn(scorers['filter v1.0'][i])} | {yn(scorers['filter v1.1'][i])} | {yn(scorers['filter v1.2'][i])} | " + " | ".join(yn(v) for v in cl) + " |")
    Path(f"out/report_{tag}.md").write_text("\n".join(md) + "\n"); Path(f"out/report_{tag}.json").write_text(json.dumps(rep, indent=1))
    print(f"wrote out/report_{tag}.md")

if __name__ == "__main__":
    main(False)
    if Path("labels/hand_corrections.jsonl").exists(): main(True)
