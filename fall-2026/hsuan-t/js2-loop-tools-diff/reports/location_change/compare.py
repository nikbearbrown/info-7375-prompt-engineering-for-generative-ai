"""Before/after for JS2 D7: what changes when check 2 reads offices too and the profile accepts "united states".

Why this exists: the change alters the rule's verdicts on JS1's own data, and JS1's submitted
runs are not rewritten. This script recomputes both versions from the saved raw files in the repo,
so anyone can re-run it and get the same table (README cites result.md).

Run from the repo root:  .venv/bin/python reports/location_change/compare.py
"""

import csv
import dataclasses
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from job_agent import inputs                       # noqa: E402
from job_agent.common.paths import Paths           # noqa: E402
from job_agent.judges import rule                  # noqa: E402
from job_agent.watch.boards import greenhouse      # noqa: E402

RUN2_RAW = ROOT / "evidence/raw/2026-10-31T225910Z/stripe_content.json"   # JS1 Run 2 (live)
LABEL_RAW = ROOT / "evidence/raw/2026-10-31T214118Z/stripe_content.json"  # the fetch the labels come from
RUN2_VERDICTS = ROOT / "runs/2026-10-31T225910Z/verdicts.json"
LABELS = ROOT / "labels/labels.csv"
JS2_ONLY_PLACE = "united states"                   # the profile word D7 added


def criteria_pair():
    """JS2 criteria as shipped, and JS1's: the same files minus the word D7 added."""
    p = Paths()
    new = inputs.load_criteria(p.default_resume, p.default_profile, p)
    old_profile = {**new.profile, "locations": [l for l in new.profile["locations"] if l != JS2_ONLY_PLACE]}
    return dataclasses.replace(new, profile=old_profile), new


def postings(raw: Path):
    """Each posting twice: as JS1 read it (location.name only) and as JS2 reads it (plus offices)."""
    body = raw.read_bytes()
    names = {j["id"]: (j.get("location") or {}).get("name") or "" for j in json.loads(body)["jobs"]}
    for p in greenhouse.parse(body):
        yield dataclasses.replace(p, location=names[p.id]), p


def compare(raw: Path, ids=None, labels=None) -> dict:
    old_c, new_c = criteria_pair()
    row = {"n": 0, "changed": 0, "rel_old": 0, "rel_new": 0, "agree_old": 0, "agree_new": 0, "diffs": []}
    for old_p, new_p in postings(raw):
        if ids is not None and old_p.id not in ids:
            continue
        a, b = rule.judge(old_p, old_c), rule.judge(new_p, new_c)
        va, vb = a.verdict["verdict"], b.verdict["verdict"]
        row["n"] += 1
        row["rel_old"] += va == "relevant"
        row["rel_new"] += vb == "relevant"
        if labels:
            row["agree_old"] += va == labels[old_p.id]
            row["agree_new"] += vb == labels[old_p.id]
        if va != vb or a.failed_check != b.failed_check:
            row["changed"] += 1
            row["diffs"].append((old_p.id, old_p.title.strip(), f"{va} @ {a.failed_check or '-'}",
                                 f"{vb} @ {b.failed_check or '-'}", labels.get(old_p.id, "") if labels else ""))
    return row


def main() -> None:
    run2_ids = {v["posting_id"] for v in json.loads(RUN2_VERDICTS.read_text())["verdicts"]}
    labels = {int(r["posting_id"]): r["label"] for r in csv.DictReader(LABELS.open())}
    rows = [
        ("Stripe, JS1 Run 2 raw, every posting", compare(RUN2_RAW), False),
        ("JS1 Run 2's 20 new postings (submitted verdicts)", compare(RUN2_RAW, run2_ids), False),
        ("My 20 hand-labeled postings", compare(LABEL_RAW, set(labels), labels), True),
    ]
    out = ["# Location change (JS2 D7): before vs after", "",
           "Before = JS1: check 2 reads `location.name`; profile locations `boston, us remote, us`.  ",
           "After = JS2: check 2 reads `location.name` + every `offices[].location`; profile adds `united states`.  ",
           "Same saved raw files for both. Generated by `compare.py`; do not edit by hand.", "",
           "| Postings | n | rule verdict or cut changed | relevant before → after | agree with my label before → after |",
           "|---|---|---|---|---|"]
    for name, r, has_labels in rows:
        agree = f"{r['agree_old']}/{r['n']} → {r['agree_new']}/{r['n']}" if has_labels else "—"
        out.append(f"| {name} | {r['n']} | {r['changed']} | {r['rel_old']} → {r['rel_new']} | {agree} |")
    out += ["", "## Changed postings among my 20 labels", "",
            "| posting_id | title | before | after | my label |", "|---|---|---|---|---|"]
    out += [f"| {i} | {t} | {a} | {b} | {l} |" for i, t, a, b, l in rows[2][1]["diffs"]]
    (Path(__file__).parent / "result.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
