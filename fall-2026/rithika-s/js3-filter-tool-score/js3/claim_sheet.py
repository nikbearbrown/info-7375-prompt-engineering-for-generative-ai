"""Write the shortlist claim sheet and a blank label file for a human.

    python3 -m js3.claim_sheet [--shortlist out/shortlist] [--labels labels]

Reads out/shortlist/shortlist.json and out/shortlist/claude_raw/*.json,
checks every quote with js3.evidence, and writes two files:

    labels/shortlist_claims_sheet.md   per posting, per claim: the claim, the
                                       quote, the automated check result and
                                       verdict, and 300 characters of context
    labels/shortlist_claim_labels.csv  posting,claim_no,label,note with every
                                       label blank (labeling is the human's)

Refuses to run if either file already exists, so labels already entered
are never overwritten; the two files are always written together. Postings
with no Claude output or with a parse error appear in the sheet but get no
label rows.
"""

import argparse
import csv
import json
import sys
from pathlib import Path

from js3 import corpus as js3_corpus
from js3 import evidence
from js3.shortlist import sha256_text

ROOT = Path(__file__).resolve().parent.parent
SHEET = "shortlist_claims_sheet.md"
LABELS = "shortlist_claim_labels.csv"
COLUMNS = ["posting", "claim_no", "label", "note"]
CONTEXT_CHARS = 300


class SheetError(Exception):
    """The sheet cannot be written."""


def posting_key(entry):
    return f"{entry['board']}__{entry['id']}"


def collect(out_dir, postings):
    """[(entry, status, result, raw)] for every shortlisted posting."""
    manifest = evidence.load_shortlist(out_dir)
    rows = []
    for entry in manifest["postings"]:
        posting = postings.get((entry["board"], str(entry["id"])))
        if posting is None:
            raise SheetError(f"{entry['board']}/{entry['id']} is not in the "
                             "frozen corpus")
        raw_path = Path(out_dir) / entry["claude_raw"]
        if not raw_path.exists():
            rows.append((entry, posting, "no Claude output", None, None))
            continue
        raw = json.loads(raw_path.read_text("utf-8"))
        prompt_path = Path(out_dir) / entry["prompt"]
        notes = []
        if raw.get("prompt_sha256") != entry["prompt_sha256"]:
            notes.append("prompt_sha256 in the raw record differs from the "
                         "shortlist prompt")
        if prompt_path.exists() and \
                sha256_text(prompt_path.read_text("utf-8")) \
                != entry["prompt_sha256"]:
            notes.append("prompt file changed since the shortlist")
        if raw.get("returncode") != 0:
            notes.append(f"claude returncode {raw.get('returncode')}")
        result = evidence.check_output(raw.get("raw_stdout"), posting)
        status = ("parse error: " + result["parse_error"]
                  if result["parse_error"] else "checked")
        rows.append((entry, posting, status, result,
                     {"raw": raw, "notes": notes}))
    return rows


def _inline(text):
    return " ".join(str(text).split()).replace("|", "\\|")


def render_sheet(rows):
    out = [
        "# Shortlist claims sheet",
        "",
        "Generated by `python3 -m js3.claim_sheet`. Claims and quotes were "
        "written by Claude (`prompts/justify-v1.md`); the *check* and "
        "*verdict* below are automated (`js3/evidence.py`) and only say "
        "whether the quote is in the posting. **A found quote is only a "
        "candidate; whether it supports the claim is for the human label "
        "in `shortlist_claim_labels.csv`.** Not found or NOT STATED means "
        "\"I cannot tell\".",
        "",
        "Context: 300 characters of the posting around the found quote; "
        "for a quote that was not found or NOT STATED, the first 300 "
        "characters of the body.",
        "",
    ]
    for entry, posting, status, result, extra in rows:
        out += [f"## {entry['rank']}. {entry['board']} / {entry['id']}: "
                f"{_inline(posting.get('title') or '')}",
                "",
                f"- posting key: `{posting_key(entry)}` · filter score "
                f"{entry['score']} · {posting.get('url') or ''}",
                f"- status: **{status}**"]
        if extra:
            for note in extra["notes"]:
                out.append(f"- warning: {note}")
        if result is None or result["parse_error"]:
            if extra:
                stdout = extra["raw"].get("raw_stdout") or ""
                out += ["", "Raw output kept as received (first 600 "
                        "characters):", "", "~~~~text",
                        stdout[:600], "~~~~"]
            out.append("")
            continue
        out.append("")
        for n, c in enumerate(result["claims"], 1):
            where = c["where"]
            loc = (f" in {where['field']} at {where['start']}-"
                   f"{where['end']}" if where else "")
            out += [f"### Claim {n}",
                    "",
                    f"- claim: {_inline(c['claim'])}",
                    f"- quote: \"{_inline(c['quote'])}\"",
                    f"- check: **{c['check']}**{loc} → verdict "
                    f"**{c['verdict']}**",
                    "- context:",
                    "",
                    "~~~~text",
                    evidence.context(posting, where, CONTEXT_CHARS),
                    "~~~~",
                    ""]
    return "\n".join(out) + "\n"


def label_rows(rows):
    return [{"posting": posting_key(entry), "claim_no": n, "label": "",
             "note": ""}
            for entry, _, _, result, _ in rows
            if result and not result["parse_error"]
            for n in range(1, len(result["claims"]) + 1)]


def write(out_dir, labels_dir, postings):
    labels_dir = Path(labels_dir)
    sheet, csv_path = labels_dir / SHEET, labels_dir / LABELS
    existing = [str(p) for p in (sheet, csv_path) if p.exists()]
    if existing:
        raise SheetError(f"refusing to overwrite {existing}; move them "
                         "aside first if you really mean to regenerate")
    rows = collect(out_dir, postings)
    labels = label_rows(rows)
    if not labels:
        raise SheetError("no parsed claims to label (run js3.shortlist "
                         "--run-claude first, or check the parse errors)")
    text = render_sheet(rows)
    with open(csv_path, "x", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS)
        writer.writeheader()
        writer.writerows(labels)
    with open(sheet, "x", encoding="utf-8") as fh:
        fh.write(text)
    return sheet, csv_path, len(labels)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--shortlist", default=None,
                        help="default <root>/out/shortlist")
    parser.add_argument("--labels", default=None,
                        help="default <root>/labels")
    parser.add_argument("--root", default=str(ROOT))
    args = parser.parse_args(argv)
    root = Path(args.root)
    out_dir = Path(args.shortlist) if args.shortlist else \
        root / "out" / "shortlist"
    labels_dir = Path(args.labels) if args.labels else root / "labels"
    try:
        postings = {(p["board"], str(p["id"])): p
                    for p in js3_corpus.load(root)["postings"]}
        sheet, csv_path, n = write(out_dir, labels_dir, postings)
    except (SheetError, OSError, ValueError, KeyError,
            js3_corpus.CorpusError) as exc:
        print(f"claim_sheet: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {sheet} and {csv_path} ({n} claims, labels blank)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
