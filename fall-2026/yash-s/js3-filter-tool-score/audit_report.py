"""The reject-audit numbers, recomputed from my hand labels (FILTER.md section 8).

    python3 audit_report.py [--sample audit/sample-filter-v1.1-2026-11-18T212545Z]

Reads my labeling sheet, the sample record and the filter run it came from, checks
that they still match, and writes audit-results.md next to the sheet. Every number
in that file comes from this script. It never changes a label.

Only random groups support an estimate about a population, and then only as a range.
The near-threshold groups were chosen on purpose and are reported as counts.
"""
import argparse
import collections
import copy
import csv
import json
import sys
from pathlib import Path

import experiment as X
import job_filter as J
import postings as P

HERE = Path(__file__).resolve().parent
DEFAULT_SAMPLE = HERE / "audit" / "sample-filter-v1.1-2026-11-18T212545Z"
RANDOM_GROUPS = ("random_reject", "kept_review_queue")
AGREE = ("correct reject", "correctly in review")


def load(sample_dir):
    sample_dir = Path(sample_dir)
    with open(sample_dir / "labeling-sheet.csv", encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    meta = json.loads((sample_dir / "sample.json").read_text(encoding="utf-8"))
    run = HERE / "runs" / meta["filter_run"]
    if P.sha256(run / "results.json") != meta["results_json_sha256"]:
        raise SystemExit("results.json no longer matches the sample record; stop")
    sheet_ids = {g: [[r["board"], r["posting_id"]] for r in rows if r["group"] == g] for g in meta["groups"]}
    if sheet_ids != meta["groups"]:
        raise SystemExit("the labeling sheet no longer lists the sampled postings; stop")
    unlabeled = [r["row"] for r in rows if not r["MY_VERDICT"].strip()]
    if unlabeled:
        raise SystemExit(f"rows without my verdict: {unlabeled}")
    results = {(r["board"], str(r["id"])): r for r in json.loads((run / "results.json").read_text(encoding="utf-8"))}
    return rows, meta, results, run


def category(row):
    v, d = row["MY_VERDICT"].strip(), row["filter_decision"]
    if v == "cannot tell":
        return "cannot tell"
    if d == "rejected":
        return "correctly rejected" if v == "correct reject" else "rejected, should have been kept for review"
    if d == "review":
        return {"correctly in review": "correctly in review: information missing",
                "should have been rejected": "in review, should have been rejected",
                "should be confirmed": "in review, should have been confirmed"}[v]
    return {"should have been rejected": "confirmed, should have been rejected"}.get(v, "confirmed, agreed")


def false_friend_effect(row, result, posting, rules):
    """Re-decide the posting with the false-friend phrase removed from the rules."""
    w = row["FALSE_FRIEND_WORD"].strip()
    r2 = copy.deepcopy(rules)
    where = None
    for cat, phrases in r2["filter"]["topics"].items():
        if not cat.startswith("_") and w in phrases:
            phrases.remove(w)
            where = f"topic phrase ({cat})"
    if w in r2["skills"]:
        r2["skills"].remove(w)
        where = "résumé skill"
    if where is None:
        return {"word": w, "where": "not a filter phrase", "effect": "nothing to remove"}
    after = J.evaluate(posting, r2)
    return {"word": w, "where": where, "score_before": result["score"], "score_after": after["score"],
            "decision_before": result["decision"], "decision_after": after["decision"],
            "effect": "changes the decision" if after["decision"] != result["decision"] else "same decision"}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--sample", default=str(DEFAULT_SAMPLE))
    ap.add_argument("--js2", default=str(P.DEFAULT_JS2))
    args = ap.parse_args(argv)
    sample_dir = Path(args.sample).resolve()
    rows, meta, results, run = load(sample_dir)
    pops = meta["population_sizes_at_draw_time"]
    groups = collections.OrderedDict((g, [r for r in rows if r["group"] == g]) for g in meta["groups"])

    L = [f"# Reject audit results: {sample_dir.name}", "",
         "Generated by `python3 audit_report.py`. Do not edit by hand; rerun it. My verdicts are in "
         "`labeling-sheet.csv`; this file only counts them.", "",
         f"- Filter run: `{meta['filter_run']}` (FILTER.md v{meta['filter_version']}); results.json sha256 "
         f"`{meta['results_json_sha256'][:12]}…`, checked.",
         f"- Labeling sheet sha256 `{P.sha256(sample_dir / 'labeling-sheet.csv')[:12]}…`; seed {meta['seed']}.",
         "- Each group was drawn from postings not already drawn, so the groups do not overlap.", "",
         "## Agreement by group", "",
         "| Group | How it was drawn | Population | Sampled | I agreed | I disagreed | Rows I disagreed with |",
         "|---|---|---:|---:|---:|---:|---|"]
    how = {"random_reject": "simple random sample of rejected postings",
           "borderline_55_to_64": "deliberate: random within scores 55-64",
           "borderline_65_to_75": "deliberate: random within scores 65-75",
           "kept_confirmed": "every confirmed posting",
           "kept_review_queue": "simple random sample of the review queue"}
    for g, rs in groups.items():
        dis = [r["row"] for r in rs if r["MY_VERDICT"].strip() not in AGREE]
        L.append(f"| {g} | {how.get(g, '')} | {pops[g]} | {len(rs)} | {len(rs) - len(dis)} | {len(dis)} | "
                 f"{', '.join(dis) or 'none'} |")

    L += ["", "## What the random samples can and cannot say", ""]
    for g in RANDOM_GROUPS:
        rs, N = groups.get(g, []), pops.get(g, 0)
        if not rs:
            continue
        x, n = sum(r["MY_VERDICT"].strip() not in AGREE for r in rs), len(rs)
        w, e = X.wilson(x, n), X.exact(x, n)
        what = "rejects I would have kept for review" if g == "random_reject" else "review-queue postings I would have rejected"
        L += [f"**{g}:** {x} of {n} sampled {what} ({x / n:.1%}). With {n} postings, the share among all {N} could "
              f"plausibly be anywhere from {w[0]:.1%} to {w[1]:.1%} (95% Wilson interval; exact Clopper-Pearson "
              f"{e[0]:.1%} to {e[1]:.1%}). That is roughly {w[0] * N:.0f} to {w[1] * N:.0f} postings. "
              f"This is a sample estimate, not a measured rate for all {N}.", ""]
    L += ["The confirmed shortlist was empty, so how often the filter wrongly confirms a posting is not measured at all.", ""]

    cats = collections.Counter(category(r) for r in rows)
    L += ["## FILTER.md section 8 categories (all 60 rows)", "", "| Category | Rows | Count |", "|---|---|---:|"]
    for c in ("rejected, should have been kept for review", "confirmed, should have been rejected",
              "correctly in review: information missing", "correctly rejected",
              "in review, should have been rejected", "in review, should have been confirmed", "cannot tell"):
        rr = [r["row"] for r in rows if category(r) == c]
        L.append(f"| {c} | {', '.join(rr) if len(rr) <= 12 else f'{len(rr)} rows'} | {cats.get(c, 0)} |")

    L += ["", "## Every disagreement", "",
          "| Row | Group | Board | Title | Filter | Score | Filter's reason | My verdict | My reason |",
          "|---:|---|---|---|---|---:|---|---|---|"]
    for r in rows:
        if r["MY_VERDICT"].strip() not in AGREE:
            L.append(f"| {r['row']} | {r['group']} | {r['board']} | {r['title']} | {r['filter_decision']} | {r['score']} | "
                     f"{r['filter_reasons'] or 'score below 65'} | {r['MY_VERDICT']} | {r['MY_REASON']} |")

    rr = groups.get("random_reject", [])
    steps = collections.Counter(r["decision_step"] for r in rr)
    first = collections.Counter((r["filter_reasons"].split(" | ")[0].split(" '")[0].split(":")[0] or "score below 65")
                                for r in rr)
    L += ["", "## What rejected the random sample", "",
          f"Step 1 (hard exclusion): {steps.get('1', 0)}; step 2 (score below 65): {steps.get('2', 0)}. "
          "First reason listed for each:", "", "| First reason | Postings |", "|---|---:|"]
    L += [f"| {k} | {v} |" for k, v in first.most_common()]

    ff_rows = [r for r in rows if r["FALSE_FRIEND_WORD"].strip()]
    if ff_rows:
        persona, _ = P.load_persona(args.js2)
        rules = J.load_rules(persona=persona)
        by_key = {(p["board"], p["id"]): p for p in P.load_saved_postings(args.js2)[0]}
        L += ["", "## False friends I named", "",
              "Each phrase is removed from the rules for that one posting and the posting is decided again, "
              "to show whether the false friend changed the outcome.", "",
              "| Row | Title | Word | Kind | Score without it | Decision without it | Effect |", "|---:|---|---|---|---|---|---|"]
        for r in ff_rows:
            k = (r["board"], r["posting_id"])
            fx = false_friend_effect(r, results[k], by_key[k], rules)
            if "score_after" in fx:
                L.append(f"| {r['row']} | {r['title']} | `{fx['word']}` | {fx['where']} | {fx['score_before']} → {fx['score_after']} | "
                         f"{fx['decision_before']} → {fx['decision_after']} | {fx['effect']} |")
            else:
                L.append(f"| {r['row']} | {r['title']} | `{fx['word']}` | {fx['where']} | | | {fx['effect']} |")
    out = sample_dir / "audit-results.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(HERE)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
