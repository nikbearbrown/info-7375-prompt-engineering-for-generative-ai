"""Write the generated tables used by AUDIT.md and SCORE.md, straight from the saved files (no hand-copied numbers).

    python3 tools/make_tables.py      # writes audit/audit-table.md and out/score-table.md
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

NAMES = {"R": "Random rejects (32)", "N": "Closest calls near the threshold (10)", "K": "Kept sample (10)",
         "T": "Cannot-tell sample (6)"}


def audit_table():
    blind = json.loads((ROOT / "out" / "audit-v1-blind.json").read_text())
    corr = {c["item"]: c for c in json.loads((ROOT / "audit" / "hand-label-corrections.json").read_text())["corrections"]}
    reasons = json.loads((ROOT / "audit" / "hand-reasons.json").read_text())["items"]
    out = ["# Audit table (generated by tools/make_tables.py from out/audit-v1-blind.json and audit/*.json)", "",
           "Filter v1 decision vs my blind hand verdict. **Corrected** = a change I made in chat after seeing the "
           "filter's verdict (not blind). Reasons are mine, verbatim, except rows marked *(general)*, where my reason "
           "was \"mostly the number of years experience\" and the years line is copied from the posting.", ""]
    for s, v in blind["strata"].items():
        out += [f"## {NAMES[s]}", "", "| # | board | title | v1 | score | my blind verdict | corrected | my reason |",
                "|---|---|---|---|---|---|---|---|"]
        for r in v["rows"]:
            c = corr.get(r["item"])
            cv = "" if not c else ("withdrawn" if "withdrawn" in c else f"→ **{c['to']}**")
            rs = reasons.get(str(r["item"]), {})
            why = rs.get("riya", "")
            if why.startswith("(general)"):
                why = "*(general)* years: " + "; ".join(rs.get("posting_years_lines", []))[:160]
            why = why.replace("|", "/")[:220]
            mark = "" if r["agree"] else " ✗"
            out.append(f"| {r['item']} | {r['board'].split(':')[1]} | {r['title'].strip()[:60]} | {r['filter']} | "
                       f"{r['score']} | {r['hand']}{mark} | {cv} | {why} |")
        out.append("")
    (ROOT / "audit" / "audit-table.md").write_text("\n".join(out) + "\n")


def score_table():
    out = ["# Held-out and dev results (generated by tools/make_tables.py from out/heldout-*.json, out/dev-*.json)", ""]
    for split in ["heldout", "dev"]:
        b = json.loads((ROOT / "out" / f"{split}-blind.json").read_text())
        c = json.loads((ROOT / "out" / f"{split}-corrected.json").read_text())
        out += [f"## {split} ({b['n_labeled']} labels)", "",
                "| scorer | agree (blind labels) | 95% interval | shows predicted / my blind shows / both | agree (corrected labels) |",
                "|---|---|---|---|---|"]
        rows = [("always \"not\" (trivial baseline)", b["always_not"], c["always_not"])]
        rows += [(f"filter {k}", v, c["filters"][k]) for k, v in b["filters"].items()]
        rows += [(f"Claude {k}", v, c["claude"][k]) for k, v in b["claude"].items()]
        for name, x, y in rows:
            out.append(f"| {name} | {x['agree']}/{x['n']} | {x['wilson95'][0]:.2f}–{x['wilson95'][1]:.2f} | "
                       f"{x['show_predicted']} / {x['show_hand']} / {x['show_both']} | {y['agree']}/{y['n']} |")
        out.append("")
    (ROOT / "out" / "score-table.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    audit_table()
    score_table()
    print("wrote audit/audit-table.md, out/score-table.md")
