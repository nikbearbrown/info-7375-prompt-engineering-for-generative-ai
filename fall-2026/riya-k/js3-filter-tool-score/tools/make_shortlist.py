"""The source-grounded shortlist: every kept posting, every claim in its justification, each labeled against the text.

    python3 tools/make_shortlist.py [--filter filters/filter-v1.json]
Writes shortlist/shortlist-<version>.json and shortlist/shortlist-<version>.md, then RECOMPUTES every label a second
way (tools/make_shortlist.py --check): each quoted piece of evidence must occur verbatim in the posting's own fields.
Offline.
"""

import argparse
import collections
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from js3 import corpus, evidence, filter as F  # noqa: E402
from js3.text import plain_text  # noqa: E402


def build(flt):
    posts = corpus.load()
    rows = []
    for p in posts:
        rec = F.apply(p, flt, evidence.claims)
        if rec["decision"] != "kept":
            continue
        rec["claims"] = evidence.claims(p, flt)
        rows.append(rec)
    rows.sort(key=lambda r: (-r["score"], r["board"], r["title"]))
    return rows


def check(rows):
    """Second way: strip the quote's ellipses and look for it, verbatim, in title + text / location / employment."""
    posts = corpus.by_key(corpus.load())
    bad = []
    for r in rows:
        p = posts[(r["board"], r["id"])]
        body = p["title"] + " " + plain_text(p.get("content", ""))
        for c in r["claims"]:
            ev = c.get("evidence")
            if ev is None:
                if c["label"] != "insufficient":
                    bad.append((r["id"], c["claim"], "no evidence but not insufficient"))
                continue
            if ev.startswith("title: "):
                ok = ev[8:-1] == p["title"]
            elif ev.startswith("location: "):
                ok = ev[11:-1] == p["location"]["name"]
            elif ev.startswith("employmentType: "):
                ok = ev[16:] == p.get("employment")
            else:
                ok = ev.strip("…").strip() in body
            if not ok:
                bad.append((r["id"], c["claim"], ev[:80]))
    return bad


def md(rows, flt):
    labels = collections.Counter(c["label"] for r in rows for c in r["claims"])
    out = [f"# Shortlist {flt['version']} (generated by tools/make_shortlist.py; do not edit by hand)", "",
           f"{len(rows)} kept postings, {sum(labels.values())} claims: "
           + ", ".join(f"{k} {v}" for k, v in sorted(labels.items())), ""]
    for r in rows:
        out.append(f"## {r['title'].strip()} · {r['board']} · score {r['score']}")
        out.append(f"`{r['id']}` · {r['location']} · counted: " + "; ".join(f"{k} {v}" for k, v in r["parts"].items() if v))
        out.append("")
        out.append("| claim | label | evidence from the posting |")
        out.append("|---|---|---|")
        for c in r["claims"]:
            ev = (c.get("evidence") or c.get("note") or "—").replace("|", "\\|")
            ev = re.sub(r"\s+", " ", ev)
            note = f" ({c['note']})" if c.get("note") and c.get("evidence") else ""
            out.append(f"| {c['claim']} | **{c['label']}** | {ev}{note} |")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--filter", default=None)
    a = ap.parse_args()
    flt = F.load_filter(a.filter)
    rows = build(flt)
    d = ROOT / "shortlist"
    d.mkdir(exist_ok=True)
    (d / f"shortlist-{flt['version']}.json").write_text(json.dumps(rows, indent=1, ensure_ascii=False) + "\n")
    (d / f"shortlist-{flt['version']}.md").write_text(md(rows, flt))
    bad = check(rows)
    labels = collections.Counter(c["label"] for r in rows for c in r["claims"])
    by_claim = collections.defaultdict(collections.Counter)
    for r in rows:
        for c in r["claims"]:
            by_claim[c["claim"][:2]][c["label"]] += 1
    print(f"{len(rows)} kept, labels {dict(labels)}")
    print({k: dict(v) for k, v in sorted(by_claim.items())})
    print(f"recompute check: {len(bad)} evidence quotes NOT found verbatim", bad[:5])
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
