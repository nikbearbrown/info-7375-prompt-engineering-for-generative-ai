#!/usr/bin/env python3
"""Assemble scenes.py = the toolkit's iso_kit.py + iso_originals_25.py (pasted, as the show-tell skill
requires: Gate A copies only scenes.py) + this reel's scenes_body.py. Run after editing scenes_body.py."""
from pathlib import Path
HERE = Path(__file__).resolve().parent
KIT = HERE.parent / "brutalist.art" / "skills" / "make" / "show-tell" / "templates"
parts = [(KIT / "iso_kit.py").read_text(), (KIT / "iso_originals_25.py").read_text(), (HERE / "scenes_body.py").read_text()]
head = ('"""scenes.py for fine-print-pitch. GENERATED by build_scenes.py: do not edit here.\n'
        'Sections: 1) brutalist.art show-tell iso_kit.py, 2) iso_originals_25.py (the approved 25 props),\n'
        '3) scenes_body.py (this film\'s 14 drawn beats)."""\n')
(HERE / "scenes.py").write_text(head + "\n\n".join(parts))
print("scenes.py:", sum(len(p) for p in parts) // 1024, "KB")
