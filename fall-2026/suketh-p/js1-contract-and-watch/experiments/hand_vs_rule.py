"""Compare the 20 labels the student supplied with the code's rule records. A consistency
check, NOT an independent one (see README, "The labels are not independent").
Writes experiments/hand-vs-rule.md.

    python3 experiments/hand_vs_rule.py
"""

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from experiments import harness  # noqa: E402
from jobwatch import rule  # noqa: E402


def main():
    selection, resume, postings = harness.selection(), harness.persona(), harness.baseline_postings()
    with open(harness.HAND_LABELS, newline="", encoding="utf-8") as handle:
        hand = {int(row["posting_id"]): row for row in csv.DictReader(handle)}
    lines = [
        "# The student's labels vs rule records",
        "",
        "The student supplied 20 labels in chat on 2026-10-31, applying [LABELING-RULE.md](../labels/LABELING-RULE.md).",
        "This table puts each label next to the record `jobwatch.rule` computes. It is a **consistency check, not an",
        "independent one**. Before the labels were written, the conversation had displayed the rule's list of relevant",
        "postings (2026-10-28), `experiments/selection.json` recorded each posting's rule category, and both judges'",
        "verdicts on 5418610008 had been reported (2026-10-31 08:49–08:53). See the README section",
        "\"The labels are not independent\". Generated by `python3 experiments/hand_vs_rule.py`.",
        "",
        "| # | Posting | Set | Title | Student's label | Student's reason | Rule | Rule's failed conditions | Same? |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    same = 0
    for n, posting_id in enumerate(selection["labeling_order"], 1):
        record = rule.rule_verdict(resume, postings[posting_id])
        row = hand[posting_id]
        match = record["verdict"] == row["label"]
        same += match
        set_name = "development" if posting_id in selection["development"] else "held-out"
        lines.append(f"| {n} | {posting_id} | {set_name} | {postings[posting_id].title.strip()} | {row['label']} | "
                     f"{row['failed_conditions'] or '—'} | {record['verdict']} | "
                     f"{', '.join(record['failed_conditions']) or '—'} | {'yes' if match else '**NO**'} |")
    lines += ["", f"**Verdicts identical on {same} of 20.**", ""]
    out = harness.ROOT / "experiments" / "hand-vs-rule.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"hand == rule on {same}/20; wrote {out.relative_to(harness.ROOT)}")


if __name__ == "__main__":
    main()
