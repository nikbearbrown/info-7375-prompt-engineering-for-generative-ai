"""Compare the student's 20 hand labels with the code's rule records: an independent hand
check of the rule implementation. Writes experiments/hand-vs-rule.md.

    python3 experiments/hand_vs_rule.py
"""

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from experiments import harness  # noqa: E402
from jobwatch import rule  # noqa: E402


def main():
    selection, resume, postings = harness.selection(), harness.persona(), harness.baseline_postings()
    with open(harness.HAND_LABELS, newline="", encoding="utf-8") as handle:
        hand = {int(row["posting_id"]): row for row in csv.DictReader(handle)}
    lines = [
        "# Hand labels vs rule records",
        "",
        "The student labeled 20 postings by reading them, applying [LABELING-RULE.md](../labels/LABELING-RULE.md);",
        "the labeling sheet showed no rule output. This table puts each hand label next to the record",
        "`jobwatch.rule` computes. Generated by `python3 experiments/hand_vs_rule.py`.",
        "",
        "| # | Posting | Set | Title | Hand label | Student's reason | Rule | Rule's failed conditions | Same? |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    same = 0
    for n, posting_id in enumerate(selection["labeling_order"], 1):
        record = rule.rule_verdict(resume, postings[posting_id])
        row = hand[posting_id]
        match = record["verdict"] == row["label"]
        same += match
        set_name = "development" if posting_id in selection["development"] else "held-out"
        lines.append(f"| {n} | {posting_id} | {set_name} | {postings[posting_id].title.strip()} | {row['label']} | "
                     f"{row['failed_conditions'] or '—'} | {record['verdict']} | "
                     f"{', '.join(record['failed_conditions']) or '—'} | {'yes' if match else '**NO**'} |")
    lines += ["", f"**Verdicts identical on {same} of 20.**", ""]
    out = harness.ROOT / "experiments" / "hand-vs-rule.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"hand == rule on {same}/20; wrote {out.relative_to(harness.ROOT)}")


if __name__ == "__main__":
    main()
