"""SEEDED demonstration: a run that ends cleanly and is wrong, and the independent check
that catches it (brief, Step 2.2; GATE.md wrong version 1).

Nothing here touches the network or the real state. In a temporary project folder:
  1. seeded-1 replays three bodies saved by the real run 2026-11-08-failure-1
     (anthropic, databricks, linear) and finishes with a SIMULATED approval, so the
     temporary state holds a baseline for all three boards;
  2. seeded-2 replays the same anthropic and databricks bodies, but Linear's body is
     replaced by a CONSTRUCTED empty response {"apiVersion": "1", "jobs": []};
  3. checks/independent_check.py (which does not import jobwatch) reads seeded-2's
     saved bodies and the state copies taken before and after it.
Everything is copied to demos/finished-wrong-answer/<label>/ with a generated SUMMARY.md.

Usage (from the js2-loop-tools-diff folder):
  python3 demos/finished_wrong_answer.py --label at-<commit>
"""

import argparse
import gzip
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT))

from jobwatch import loop, net  # noqa: E402
from jobwatch.policy import Approval  # noqa: E402

SOURCE_RUN = PROJECT / "runs" / "2026-11-08-failure-1"
URLS = {
    "greenhouse-anthropic": "https://boards-api.greenhouse.io/v1/boards/anthropic/jobs?content=true",
    "greenhouse-databricks": "https://boards-api.greenhouse.io/v1/boards/databricks/jobs?content=true",
    "ashby-linear": "https://api.ashbyhq.com/posting-api/job-board/linear",
}
EMPTY_LINEAR = b'{"apiVersion": "1", "jobs": []}'  # CONSTRUCTED, not a real response
NORMAL = ["greenhouse/anthropic", "greenhouse/databricks", "ashby/linear"]


def saved_body(name):
    return gzip.decompress((SOURCE_RUN / "raw" / f"{name}.body.gz").read_bytes())


def replay(bodies):
    def fetch(url, deadline):
        return net.Response(200, bodies[url], "application/json; charset=utf-8", None)
    return fetch


def main():
    parser = argparse.ArgumentParser(description="SEEDED finished-wrong-answer demonstration")
    parser.add_argument("--label", required=True, help="output folder name, e.g. at-<commit>")
    out = PROJECT / "demos" / "finished-wrong-answer" / parser.parse_args().label
    if out.exists():
        sys.exit(f"{out} exists; choose another --label")

    real = {URLS[name]: saved_body(name) for name in URLS}
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp).resolve() / "project"
        (root / "persona").mkdir(parents=True)
        shutil.copy(PROJECT / "persona" / "alex_morgan.json", root / "persona" / "alex_morgan.json")

        first = loop.run(root=root, run_id="seeded-1", requested=NORMAL, fetch=replay(real),
                         approval=Approval("seeded-1", "state/state.json"))  # SIMULATED approval
        before = (root / "state" / "state.json").read_bytes()

        emptied = dict(real, **{URLS["ashby-linear"]: EMPTY_LINEAR})
        second = loop.run(root=root, run_id="seeded-2", requested=NORMAL, fetch=replay(emptied),
                          approval=Approval("seeded-2", "state/state.json"))  # SIMULATED approval
        after = (root / "state" / "state.json").read_bytes()

        out.mkdir(parents=True)
        # seeded-1 only sets up the baseline; its raw bodies are the real run's, so they are not copied again.
        shutil.copytree(root / "runs" / "seeded-1", out / "seeded-1", ignore=shutil.ignore_patterns("raw"))
        shutil.copytree(root / "runs" / "seeded-2", out / "seeded-2")
        (out / "state-before-seeded-2.json").write_bytes(before)
        (out / "state-after-seeded-2.json").write_bytes(after)

    check = subprocess.run([sys.executable, "-I", str(PROJECT / "checks" / "independent_check.py"),
                            str(out / "seeded-2"), "--state-before", str(out / "state-before-seeded-2.json"),
                            "--state-after", str(out / "state-after-seeded-2.json")],
                           capture_output=True, text=True)
    (out / "independent-check.txt").write_text(f"exit status: {check.returncode}\n{check.stdout}{check.stderr}")

    linear = next(b for b in second["boards"] if b["board"] == "ashby/linear")
    summary = [
        f"# SEEDED finished-wrong-answer demonstration: `{out.name}`",
        "",
        "Generated by `demos/finished_wrong_answer.py`. **Seeded, not live**: bodies replayed from the real run "
        "`runs/2026-11-08-failure-1`, Linear's body in seeded-2 replaced by a CONSTRUCTED empty response, "
        "approvals SIMULATED, all in a temporary folder.",
        "",
        f"- seeded-1 (baseline): **{first['status']}**; state advanced: {first['state_advanced']}",
        f"- seeded-2 (Linear emptied): **{second['status']}**: {second['reason']}; "
        f"state advanced: {second['state_advanced']}",
        f"- The agent's own report on Linear in seeded-2: outcome `{linear['outcome']}`, jobs {linear['jobs']}, "
        f"new postings {linear['new_keys']}",
        f"- Independent check on seeded-2: exit {check.returncode}",
        "",
        "```text",
        check.stdout.rstrip(),
        "```",
        "",
    ]
    (out / "SUMMARY.md").write_text("\n".join(summary))
    print("\n".join(summary))
    return 0


if __name__ == "__main__":
    sys.exit(main())
