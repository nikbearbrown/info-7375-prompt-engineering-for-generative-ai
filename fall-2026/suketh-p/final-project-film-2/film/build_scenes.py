#!/usr/bin/env python3
"""Assemble scenes.py = the toolkit's iso_kit.py + iso_originals_25.py (pasted, as the show-tell skill
requires: Gate A copies only scenes.py) + this reel's scene_data.py (stamps, part tags and the terminal replays,
regenerated here by make_scene_data.py from beat_sheet.json and ../evidence/terminal/) + scenes_body.py.
Run after editing scenes_body.py."""
import json
import subprocess
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
KIT = HERE.parent / "brutalist.art" / "skills" / "make" / "show-tell" / "templates"
subprocess.run([sys.executable, str(HERE / "make_scene_data.py")], check=True)
parts = [(KIT / "iso_kit.py").read_text(), (KIT / "iso_originals_25.py").read_text(),
         (HERE / "scene_data.py").read_text(), (HERE / "scenes_body.py").read_text()]
# B17 (the student's own bar) joins only once the sheet has it, so a render can never slot a B17 without the words
if any(b["beat_id"] == "B17" for b in json.loads((HERE / "beat_sheet.json").read_text())["beats"]):
    parts.append((HERE / "scene_b17_bar.py").read_text())
head = ('"""scenes.py for fine-print-film. GENERATED by build_scenes.py: do not edit here.\n'
        'Sections: 1) brutalist.art show-tell iso_kit.py, 2) iso_originals_25.py (the approved 25 props),\n'
        '3) scene_data.py (stamps, part tags, terminal replays; generated by make_scene_data.py),\n'
        '4) scenes_body.py (this film\'s drawn beats), 5) scene_b17_bar.py once the sheet has B17."""\n')
(HERE / "scenes.py").write_text(head + "\n\n".join(parts))
print("scenes.py:", sum(len(p) for p in parts) // 1024, "KB")
