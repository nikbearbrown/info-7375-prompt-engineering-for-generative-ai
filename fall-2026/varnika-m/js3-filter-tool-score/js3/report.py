"""Write the source-grounded shortlist (shortlist/SHORTLIST.md) from FILTER.md v1.

    python3 -m js3.report shortlist
"""

import collections
import sys

from js3.claims import answer, label_claims
from js3.filter import VERSION, run_filter
from js3.load import FOLDER, RUN, load, load_persona


def shortlist_md():
    postings, not_checked = load()
    results, shortlist = run_filter(postings, load_persona())
    counts = collections.Counter(r["outcome"] for r in results.values())
    labels, answers, rows = collections.Counter(), collections.Counter(), []
    for n, item in enumerate(shortlist, 1):
        p, result = item["posting"], item["result"]
        claims = label_claims(p, result)
        verdict = answer(claims)
        labels.update(c["label"] for c in claims)
        answers[verdict["answer"]] += 1
        rows += ["## %d. %s — %s" % (n, p["company_name"], p["title"].strip()), "",
                 "%d posting id(s): %s · %s · [posting](%s)" % (len(item["ids"]), ", ".join(item["ids"]),
                                                                " | ".join(l or "" for l in item["locations"]),
                                                                p["absolute_url"]), "",
                 "**Answer: %s**%s" % (verdict["answer"], (" (" + "; ".join(verdict["because"]) + ")")
                                       if verdict["because"] else ""), "",
                 "| Claim | Label | Quote from the posting | Why |", "|---|---|---|---|"]
        for c in claims:
            quote = (c["quote"] or "—").replace("|", "/")
            rows.append("| %s %s | **%s** | %s | %s |" % (c["claim"], c["text"], c["label"],
                                                         quote[:220] + ("…" if len(quote) > 220 else ""), c["why"]))
        rows.append("")
    head = ["# Shortlist — FILTER.md %s, run %s" % (VERSION, RUN), "",
            "Generated by `python3 -m js3.report shortlist` from the saved responses. Every claim is labeled "
            "against the posting's own text (FILTER.md section 2), with the quote that decides it.", "",
            "- **Postings:** %d. Keep %d, close call %d, reject %d, cannot tell %d. Not checked: %s." % (
                len(postings), counts["keep"], counts["close_call"], counts["reject"], counts["cannot_tell"],
                ", ".join(not_checked) or "none"),
            "- **Shortlist:** %d jobs (the %d kept postings, grouped: same company, title and description)." % (
                len(shortlist), counts["keep"]),
            "- **Claims:** %d supported, %d contradicted, %d insufficient." % (
                labels["supported"], labels["contradicted"], labels["insufficient"]),
            "- **Answers:** %s." % ", ".join("%s %d" % (k, v) for k, v in answers.most_common()), "",
            "The answer is the evidence rules' output, not mine. Whether a posting is worth my time is my "
            "decision.", ""]
    (FOLDER / "shortlist").mkdir(exist_ok=True)
    (FOLDER / "shortlist" / "SHORTLIST.md").write_text("\n".join(head + rows), encoding="utf-8")
    print("\n".join(head[4:9]))
    return 0


if __name__ == "__main__":
    sys.exit({"shortlist": shortlist_md}[sys.argv[1]]())
