"""The reject audit, from Shreyash's hand verdicts (labels/hand-verdicts.jsonl) against filter v1
(results/filter-v1/records.jsonl), part by part as labels/SAMPLE-PLAN.md drew them.

A hand "yes" on a posting the filter rejected is a miss (false negative); a hand "no" on a posting it
kept is a false positive; "cannot tell" is counted separately and is never read as either. Only part
A1 (30 uniform random rejects) supports a rate; the other parts are counts.

  python3 -m js3 audit      writes results/audit-v1.{json,md}
"""
import json
import pathlib

from js3 import audit

HERE = pathlib.Path(__file__).resolve().parent.parent


def load_verdicts(path=HERE / "labels" / "hand-verdicts.jsonl"):
    out = {}
    for line in path.read_text().splitlines():
        if line.strip():
            a = json.loads(line)
            out[a["key"]] = a  # the last answer for a posting counts; earlier ones stay in the file
    return out


def compare(keys, records, verdicts):
    rows = []
    for k in keys:
        r, h = records[k], verdicts.get(k)
        hv = h["verdict"] if h else None
        if hv is None:
            kind = "not labeled"
        elif hv == "cannot tell":
            kind = "hand: cannot tell"
        elif r["verdict"] == "Relevant":
            kind = "agree" if hv == "yes" else "false positive (kept, hand says no)"
        else:
            kind = "agree" if hv == "no" else "miss (rejected, hand says yes)"
        rows.append({"key": k, "title": r["title"], "filter": r["verdict"], "failed": r["failed"],
                     "unsure": r["unsure"], "hand": hv, "note": (h or {}).get("note", ""), "kind": kind,
                     "why_filter": "; ".join(f"R{l['n']} {l['detail']}" for l in r["rules"] if l["outcome"] != "pass")})
    return rows


def part_summary(rows):
    s = {"n": len(rows)}
    for kind in ("agree", "miss (rejected, hand says yes)", "false positive (kept, hand says no)",
                 "hand: cannot tell", "not labeled"):
        s[kind] = sum(r["kind"] == kind for r in rows)
    return s


def report():
    sample = json.loads((HERE / "labels" / "sample.json").read_text())
    records = {r["key"]: r for r in audit.load_records()}
    verdicts = load_verdicts()
    a, h = sample["audit"], sample["held_out"]
    parts = {"A1 random rejects": a["random_rejects"], "A2 closest calls": a["closest_calls"], "A3 kept": a["kept"],
             "H held-out (all)": sorted(set().union(*h.values()))}
    out = {"labeled": sum(k in verdicts for k in sample["label_order"]), "to_label": sample["items"], "parts": {}}
    for name, keys in parts.items():
        rows = compare(keys, records, verdicts)
        out["parts"][name] = {"summary": part_summary(rows), "rows": rows}
    a1 = out["parts"]["A1 random rejects"]["summary"]
    n_judged = a1["n"] - a1["hand: cannot tell"] - a1["not labeled"]
    k = a1["miss (rejected, hand says yes)"]
    pool = sample["strata_sizes"]["rejects"] - len(set().union(*h.values()) & set(r for r in records if records[r]["verdict"] == "Not Relevant"))
    lo, hi = audit.wilson(k, n_judged) if n_judged else (0, 1)
    up = audit.clopper_pearson_upper(k, n_judged) if n_judged else 1.0
    out["rate"] = {"misses": k, "judged": n_judged, "cannot_tell": a1["hand: cannot tell"], "reject_pool": pool,
                   "point": k / n_judged if n_judged else None, "wilson95": [lo, hi], "one_sided_upper95": up,
                   "misses_in_pool_point": round(pool * k / n_judged, 1) if n_judged else None,
                   "misses_in_pool_upper95": round(pool * up, 1)}
    return out


def markdown(out):
    r = out["rate"]
    L = ["# Reject audit, filter v1 (generated by `python3 -m js3 audit`)", "",
         f"Hand verdicts: {out['labeled']} of {out['to_label']} postings labeled by Shreyash (labels/hand-verdicts.jsonl).", "",
         "## The rate (part A1 only)", "",
         f"- Misses among the {r['judged']} random rejects Shreyash judged yes or no: **{r['misses']}** "
         f"({r['cannot_tell']} answered 'cannot tell', not counted either way).",
         f"- 95% Wilson interval for the miss rate: {r['wilson95'][0]:.1%} to {r['wilson95'][1]:.1%}; "
         f"one-sided 95% upper bound {r['one_sided_upper95']:.1%}.",
         f"- Over the {r['reject_pool']} rejects this sample was drawn from, that is about "
         f"{r['misses_in_pool_point']} missed postings, and the sample cannot rule out up to {r['misses_in_pool_upper95']}.", ""]
    for name, part in out["parts"].items():
        s = part["summary"]
        L += [f"## {name}", "", " · ".join(f"{k}: {v}" for k, v in s.items()), "",
              "| Posting | Filter | Hand | Kind | Filter's reasons | Hand note |", "|---|---|---|---|---|---|"]
        for row in part["rows"]:
            L.append(f"| `{row['key']}` {row['title'][:60].replace('|', '/')} | {row['filter']} {row['failed'] or ''} | "
                     f"{row['hand']} | {row['kind']} | {row['why_filter'][:200].replace('|', '/')} | {row['note'].replace('|', '/')} |")
        L.append("")
    return "\n".join(L) + "\n"


def main(argv=()):
    out = report()
    res = HERE / "results"
    (res / "audit-v1.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    (res / "audit-v1.md").write_text(markdown(out))
    r = out["rate"]
    print(f"labeled {out['labeled']}/{out['to_label']}; A1 misses {r['misses']}/{r['judged']} "
          f"(Wilson95 {r['wilson95'][0]:.3f}-{r['wilson95'][1]:.3f}, upper95 {r['one_sided_upper95']:.3f})")
    for name, part in out["parts"].items():
        print(" ", name, part["summary"])
    return 0
