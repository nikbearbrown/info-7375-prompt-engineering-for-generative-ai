"""The source-grounded shortlist (Chapter 7): every posting filter v1 kept, with every claim of its
justification labeled supported / contradicted / insufficient against the posting's own text
(js3/claims.py), the agent's answer under the abstention rule, and a check that no quote is made up.

  python3 -m js3 shortlist [--filter filter-v1.json]   writes results/shortlist-<version>.{json,md}
"""
import json
import pathlib

from js3 import claims, corpus, filtering

HERE = pathlib.Path(__file__).resolve().parent.parent


def build(cfg_path="filter-v1.json"):
    cfg = filtering.load_config(HERE / cfg_path)
    persona = json.loads((HERE / "persona" / "alex_morgan.json").read_text())
    out = []
    for p in corpus.load():
        rec = filtering.evaluate(p, persona, cfg)
        if rec["verdict"] != "Relevant":
            continue
        j = claims.justify(p, rec, persona, cfg)
        out.append({"key": p["key"], "title": p["title"], "url": p.get("url"),
                    "open_in_latest_run": p["open_in_latest_run"], "last_seen": p["last_seen"],
                    "answer": j["answer"], "abstain_because": j["abstain_because"],
                    "made_up_quotes": claims.verify(j, p), "claims": j["claims"]})
    return cfg, out


def cell(s, n=170):
    s = (s or "").replace("|", "/").replace("\n", " ")
    return s if len(s) <= n else s[:n - 1] + "…"


def markdown(cfg, items):
    L = [f"# Shortlist, filter {cfg['version']} (generated by `python3 -m js3 shortlist`)", "",
         f"{len(items)} postings kept; {sum(i['open_in_latest_run'] for i in items)} still open in the latest run. "
         "Labels are the code's (js3/claims.py), against the posting's own text. Quotes are exact slices of "
         "the posting; every one was checked to be in the field it names.", ""]
    for i in items:
        state = "open" if i["open_in_latest_run"] else f"closed since {i['last_seen']}: not shortlisted"
        L += [f"## {i['title']}", "", f"`{i['key']}` ({state}) · {i['url']}", "",
              f"**Agent's answer: {i['answer']}**" + (f" because {', '.join(i['abstain_because'])}" if i["abstain_because"] else ""),
              f" · made-up quotes: {len(i['made_up_quotes'])}", "",
              "| Claim | Must-have | Label | Quote(s) from the posting | Why |", "|---|---|---|---|---|"]
        for c in i["claims"]:
            qs = []
            for e in c["supporting"]:
                if e["quote"] not in [x for _, x in qs]:
                    qs.append(("for", e["quote"]))
            for e in c["contradicting"]:
                qs.append(("against", e["quote"]))
            qtext = " ◇ ".join(f"{side}: \"{cell(x, 140)}\"" for side, x in qs[:3]) or "(none)"
            label = c["label"] + (" (conflict)" if c["conflict"] else "") + (f" (exception {c['exception'][:1]})" if c["exception"] else "")
            L.append(f"| {cell(c['claim'], 90)} | {'yes' if c['must_have'] else 'no'} | {label} | {qtext} | {cell(c['why'], 160)} |")
        L.append("")
    return "\n".join(L) + "\n"


def main(argv=()):
    cfg_path = argv[argv.index("--filter") + 1] if "--filter" in argv else "filter-v1.json"
    cfg, items = build(cfg_path)
    out = HERE / "results"
    out.mkdir(exist_ok=True)
    (out / f"shortlist-{cfg['version']}.json").write_text(json.dumps(items, indent=1, ensure_ascii=False) + "\n")
    (out / f"shortlist-{cfg['version']}.md").write_text(markdown(cfg, items))
    fake = sum(len(i["made_up_quotes"]) for i in items)
    print(f"shortlist {cfg['version']}: {len(items)} kept, answers {[i['answer'] for i in items]}, made-up quotes {fake}")
    return 1 if fake else 0
