"""Run one filter version over all 805 postings.

Writes runs/<version>/: decisions-dev.json (the 775 non-held-out decisions), heldout-decisions.sealed.json
(the 30 held-out decisions, not to be opened until CHANGE.md freezes a comparison), summary.md and
location-coverage.md (every distinct location value and how the filter read it).

    python3 -m jobfilter.run v1.0
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

from .corpus import HERE, load
from .filter import Filter, load_config, rank
from .heldout import heldout_keys

RUNS = HERE / "runs"


def run(version: str) -> dict:
    corpus = load()
    f = Filter(load_config(version))
    decisions = f.run(corpus["postings"])
    held = heldout_keys()
    dev = [d for d in decisions if d["key"] not in held]
    sealed = [d for d in decisions if d["key"] in held]
    out = RUNS / version
    out.mkdir(parents=True, exist_ok=True)
    (out / "decisions-dev.json").write_text(json.dumps(dev, indent=1, ensure_ascii=False) + "\n")
    (out / "heldout-decisions.sealed.json").write_text(json.dumps(sealed, indent=1, ensure_ascii=False) + "\n")

    c = collections.Counter(d["decision"] for d in dev)
    by_board = collections.Counter((d["key"].split("/")[1], d["decision"]) for d in dev)
    reasons = collections.Counter((d["decision"], d["reasons"][0]) for d in dev)
    lines = [f"# Filter {version} over the corpus", "",
             f"Generated by `python3 -m jobfilter.run {version}`. Corpus: 805 postings collected 2026-11-09 "
             "(JS2 live run). One expected source failed (`greenhouse/klaviyo-nonexistent-js2`, deliberate), so "
             "coverage is 5 of 6 configured boards. This is a historical snapshot, not proof that any job is still open.",
             "", f"The 30 held-out postings were scored but sealed in `heldout-decisions.sealed.json`. "
             "Every count below covers the **775 development postings** only.", "",
             "| Decision | Count |", "|---|---:|"]
    lines += [f"| {k} | {c[k]} |" for k in ("KEEP", "REVIEW", "REJECT")]
    lines += ["", "| Board | KEEP | REVIEW | REJECT |", "|---|---:|---:|---:|"]
    for b in sorted({k[0] for k in by_board}):
        lines.append(f"| {b} | {by_board[(b, 'KEEP')]} | {by_board[(b, 'REVIEW')]} | {by_board[(b, 'REJECT')]} |")
    lines += ["", "## First reason per decision", "", "| Decision | First reason | Count |", "|---|---|---:|"]
    lines += [f"| {d} | {r} | {n} |" for (d, r), n in sorted(reasons.items(), key=lambda x: -x[1])]
    lines += ["", "## Ranked shortlist (KEEP, development postings)", "",
              "| # | Score | Title + topics + location | Location | Topic groups | Key |", "|---:|---:|---:|---|---|---|"]
    for i, d in enumerate(rank(dev), 1):
        comp = d["components"]
        lines.append(f"| {i} | {d['score']} | {comp['title']}+{comp['topics']}+{comp['location']} | "
                     f"{d['location']['best']['value']} | {', '.join(t['group'] for t in d['topics'])} | "
                     f"`{d['key']}` {d['title']} |")
    (out / "summary.md").write_text("\n".join(lines) + "\n")

    vals = collections.Counter()
    for p in corpus["postings"]:
        for field, v in f.location_values(p):
            r = f.classify_location_value(v)
            vals[(r["kind"], r["score"], v)] += 1
    loc = [f"# Location values read by {version}", "",
           "Every distinct location alternative in all 805 postings (held-out included: these are field values, "
           "not decisions), with how the filter classified it. Measured over every value, not a sample.", "",
           "| Kind | Score | Postings | Value |", "|---|---:|---:|---|"]
    loc += [f"| {k} | {'' if s is None else s} | {n} | {v} |" for (k, s, v), n in sorted(vals.items(), key=lambda x: (x[0][0], x[0][2]))]
    (out / "location-coverage.md").write_text("\n".join(loc) + "\n")
    return {"dev": c, "n_dev": len(dev), "n_sealed": len(sealed)}


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print("usage: python3 -m jobfilter.run VERSION", file=sys.stderr)
        return 2
    r = run(argv[0])
    print(f"{argv[0]}: dev {r['n_dev']} {dict(r['dev'])}; held-out sealed {r['n_sealed']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
