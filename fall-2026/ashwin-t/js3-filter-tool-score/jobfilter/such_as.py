"""Relevance is not entailment, measured: which KEEPs rest on topic words found only in example lists?

A topic match like "message queues such as celery, kafka, sqs, rabbitmq, or redis" proves the word Redis appears.
It does not show the job needs Redis: the posting offers it as one example among alternatives. This module flags a
topic hit as an *example-list hit* when its saved snippet puts "such as", "e.g." or "for example" before the
alias, and recomputes each KEEP's score without those hits. It changes no decision; it only reports.

    python3 -m jobfilter.such_as v1.0      # writes shortlist/RELEVANCE-EXAMPLE-LISTS.md
"""
import json
import re
import sys
from pathlib import Path

from .corpus import HERE

MARKERS = ("such as", "e.g.", "for example", "including")


def is_example_hit(hit: dict) -> bool:
    """True when the matched alias is an item in a list opened by an example marker.

    Between the marker and the alias there may be only short comma-separated items, and "and"/"or" may appear
    only as the last connector right before the alias. Postings lose their line breaks when saved, so without this
    check a word on the next bullet ("... and spark docker and kubernetes") would wrongly count as a list item.
    """
    snippet, alias = hit.get("snippet", "").lower(), hit.get("alias", "").lower()
    pos = snippet.find(alias)
    if pos < 0:
        return False
    before = snippet[:pos]
    for marker in MARKERS:
        m = before.rfind(marker)
        if m < 0:
            continue
        segment = before[m + len(marker):]
        if re.search(r"[.;:!?•]", segment):
            continue
        segment = re.sub(r"(,\s*)?\b(and|or)\s*$", ",", segment.strip())
        items = [i.strip() for i in segment.split(",") if i.strip()]
        if all(len(i.split()) <= 3 and not re.search(r"\b(and|or)\b", i) for i in items):
            return True
    return False


def without_example_hits(decision: dict, weights: dict) -> dict:
    """Recompute topics and score with example-list hits removed. Threshold and gate are unchanged."""
    kept = [t for t in decision["topics"] if not is_example_hit(t)]
    groups = len({t["group"] for t in kept})
    topic_points = min(groups * weights["topic"], weights["topic_cap"])
    score = decision["components"]["title"] + topic_points + decision["components"]["location"]
    enough = groups >= weights["min_topic_groups"]
    return {"groups_without": groups, "score_without": score, "enough_groups": enough,
            "would_keep": enough and score >= weights["threshold"],
            "example_groups": sorted({t["group"] for t in decision["topics"] if is_example_hit(t)})}


def analyse(version: str = "v1.0") -> list:
    weights = json.loads((HERE / "filters" / f"{version}.json").read_text())["weights"]
    decisions = json.loads((HERE / "runs" / version / "decisions-dev.json").read_text())
    rows = []
    for d in decisions:
        if d["decision"] != "KEEP":
            continue
        rows.append({"key": d["key"], "title": d["title"], "score": d["score"],
                     "groups": d["n_topic_groups"], **without_example_hits(d, weights)})
    return sorted(rows, key=lambda r: (-r["score"], r["key"]))


def write_report(version: str = "v1.0") -> Path:
    rows = analyse(version)
    affected = [r for r in rows if r["example_groups"]]
    lost = [r for r in rows if not r["would_keep"]]
    lines = [
        f"# Relevance is not entailment: example-list topic matches ({version} KEEPs)",
        "",
        f"Generated by `python3 -m jobfilter.such_as {version}` from `runs/{version}/decisions-dev.json`. "
        "Computed by code from committed files; no labels and no model call.",
        "",
        "A topic hit counts as an **example-list hit** when its saved snippet has \"such as\", \"e.g.\", "
        "\"for example\" or \"including\" before the matched word, with no sentence break between. Such a hit "
        "shows the word appears, not that the job requires it. This report recomputes each KEEP without those "
        "hits. It changes no decision and no filter file.",
        "",
        f"- KEEPs: {len(rows)}",
        f"- KEEPs with at least one example-list hit: {len(affected)}",
        f"- KEEPs that would drop below the threshold or the 2-group minimum without them: {len(lost)}",
        "",
        "| Key | Title | Score | Groups | Example-list groups | Score without | Groups without | Still KEEP |",
        "|---|---|---:|---:|---|---:|---:|---|",
    ]
    for r in rows:
        lines.append(f"| `{r['key']}` | {r['title']} | {r['score']} | {r['groups']} | "
                     f"{', '.join(r['example_groups']) or '-'} | {r['score_without']} | {r['groups_without']} | "
                     f"{'yes' if r['would_keep'] else '**no**'} |")
    decisions = {d["key"]: d for d in json.loads((HERE / "runs" / version / "decisions-dev.json").read_text())}
    lines += ["", "## Every example-list snippet behind these numbers", "",
              "Read these before trusting the table: the rule is a text heuristic, not a judgment.", ""]
    seen = set()
    for r in affected:
        for t in decisions[r["key"]]["topics"]:
            norm = " ".join(t["snippet"].split())
            if is_example_hit(t) and (t["group"], norm) not in seen:
                seen.add((t["group"], norm))
                lines.append(f"- **{t['group']}**: \"{norm}\"")
    out = HERE / "shortlist" / "RELEVANCE-EXAMPLE-LISTS.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


if __name__ == "__main__":
    print(write_report(sys.argv[1] if len(sys.argv) > 1 else "v1.0"))
