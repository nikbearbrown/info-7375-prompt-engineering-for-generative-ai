"""Held-out comparison of two frozen filter versions (FILTER.md section 8).

    python3 -m jobfilter.compare v1.0 v1.1     # writes changes/HELDOUT-v1.0-vs-v1.1.md

Opens both versions' sealed held-out decisions and Ashwin's held-out labels (labels/heldout-sheet.csv, committed alone
at 9757ee7b). Run only after the second version was frozen in a commit (v1.1: 78adf4b9). The set is reported as
potentially contaminated (drafting/EVALUATION-SETS.md), never as clean held-out performance.
"""
from __future__ import annotations

import json
import sys

from .corpus import HERE
from .filter import KEEP, REJECT, REVIEW
from .sheets import read_verdicts

LABELS = ("Y", "N", "?")


def table(decisions: dict, labels: dict) -> dict:
    t = {(d, l): 0 for d in (KEEP, REVIEW, REJECT) for l in LABELS}
    for k, lab in labels.items():
        t[(decisions[k]["decision"], lab["verdict"])] += 1
    return t


def ratio(k: int, n: int) -> str:
    return "undefined (0 / 0)" if n == 0 else f"{k} / {n} = {100 * k / n:.1f}%"


def metrics(t: dict) -> dict:
    tp, fp, fn = t[(KEEP, "Y")], t[(KEEP, "N")], t[(REJECT, "Y")] + t[(REVIEW, "Y")]
    return {"precision": ratio(tp, tp + fp), "recall": ratio(tp, tp + fn),
            "review": f"{sum(t[(REVIEW, l)] for l in LABELS)} of {sum(t.values())}",
            "unknown": f"{sum(t[(d, '?')] for d in (KEEP, REVIEW, REJECT))} labeled ?"}


def write(a: str, b: str) -> str:
    labels = read_verdicts(HERE / "labels" / "heldout-sheet.csv")
    dec = {v: {d["key"]: d for d in json.loads((HERE / "runs" / v / "heldout-decisions.sealed.json").read_text())}
           for v in (a, b)}
    assert set(labels) == set(dec[a]) == set(dec[b]), "held-out keys disagree"
    L = [f"# Held-out comparison: filter {a} vs {b} (potentially contaminated)", "",
         f"Generated by `python3 -m jobfilter.compare {a} {b}` from Ashwin's 30 held-out labels "
         "(`labels/heldout-sheet.csv`, committed alone at `9757ee7b`) and each version's sealed held-out decisions.", "",
         "**Potentially contaminated.** The AI-assisted audit verdicts were inferred from these labels, and Claude Code "
         "saw the labels before the change was chosen. One held-out posting has the title the change targets. "
         "Read this as a development-style check, not clean held-out performance (`drafting/EVALUATION-SETS.md`).", "",
         "The held-out draw was stratified: 20 postings from engineering-like titles and 10 others (`jobfilter/heldout.py`). "
         "So these rates describe that draw, not all 805 postings.", ""]
    for v in (a, b):
        t = table(dec[v], labels)
        m = metrics(t)
        L += [f"## {v}", "", "| Filter \\ label | Y | N | ? |", "|---|---:|---:|---:|"]
        L += [f"| {d} | {t[(d, 'Y')]} | {t[(d, 'N')]} | {t[(d, '?')]} |" for d in (KEEP, REVIEW, REJECT)]
        L += ["", f"- Precision on known labels (KEEP that are Y, among KEEP labeled Y or N): {m['precision']}",
              f"- Recall on known labels (Y that were kept, among all Y): {m['recall']}",
              f"- REVIEW: {m['review']} · {m['unknown']}", ""]
    moved = [k for k in labels if dec[a][k]["decision"] != dec[b][k]["decision"]]
    L += ["## Every held-out posting whose decision changed", "", "| Key | Title | Label | " + a + " | " + b + " |",
          "|---|---|---|---|---|"]
    L += [f"| `{k}` | {dec[b][k]['title']} | {labels[k]['verdict']} | {dec[a][k]['decision']}: {dec[a][k]['reasons'][0]} | "
          f"{dec[b][k]['decision']}: {dec[b][k]['reasons'][0]} |" for k in sorted(moved)]
    if not moved:
        L.append("| (none) | | | | |")
    L += ["", f"## Every held-out posting labeled Y, under {b}", "", "| Key | Title | Decision | First reason |",
          "|---|---|---|---|"]
    L += [f"| `{k}` | {dec[b][k]['title']} | {dec[b][k]['decision']} | {dec[b][k]['reasons'][0]} |"
          for k in sorted(labels) if labels[k]["verdict"] == "Y"]
    out = HERE / "changes" / f"HELDOUT-{a}-vs-{b}.md"
    out.write_text("\n".join(L) + "\n")
    return out.name


if __name__ == "__main__":
    a, b = sys.argv[1:3]
    print("changes/" + write(a, b), "written")
