"""Score audit verdicts against filter v1.0 (numbers only, no judgment).

    write_report()                 hand verdicts, labels/audit-sheet.csv          -> audit/REPORT-v1.0.md
    write_report("ai-assisted")    labels/audit-ai-assisted.csv (Codex, from held-out labels)
                                                                                  -> audit/EXPLORATORY-v1.0-ai-assisted.md

Every count has its denominator. Only random strata get an interval; purposive strata are listed, never pooled.
"""
from __future__ import annotations

import json

from .audit import LABELS, SELECTION, VERSION, tally, wilson
from .corpus import HERE, load
from .audit_batches import MINIMUM_STRATA, minimum_keys
from .sheets import read_verdicts

AUDIT = HERE / "audit"


def pct(x):
    return "undefined" if x is None else f"{100 * x:.1f}%"


SOURCES = {
    "hand": (LABELS / "audit-sheet.csv", f"REPORT-{VERSION}.md",
             f"# Reject audit of filter {VERSION}: numbers",
             "Generated by `python3 -m jobfilter.audit --report` from Ashwin's recorded personal verdicts in "
             "`labels/audit-sheet.csv`. AI-assisted verdicts (`labels/audit-ai-assisted.csv`, `labels/audit-ai-draft.csv`) "
             "are not read by this report. Row notes record prior AI exposure and review timing; personal review after exposure is not a blind independent judgment."),
    "ai-assisted": (LABELS / "audit-ai-assisted.csv", f"EXPLORATORY-{VERSION}-ai-assisted.md",
                    f"# Exploratory audit of filter {VERSION} with AI-assisted verdicts (not a hand-judged audit)",
                    "**Provenance.** Every verdict here is a Codex suggestion inferred from Ashwin's 30 held-out labels, "
                    "supplied by Ashwin in chat on 2026-11-25 (`labels/audit-ai-assisted.csv`). Ashwin states they are "
                    "not independent hand judgments. The numbers below measure agreement between these AI-assisted "
                    "verdicts and the filter. They are not a human-judged error count. This file preserves the original AI-assisted analysis. Ashwin subsequently confirmed personal review "
                    "of all 47 required sample rows on 2026-11-25; see REPORT-v1.0.md. That review followed AI suggestions "
                    "and disclosure of filter results, so it is retrospective rather than blind. Any rule change based on this file makes the original 30-posting held-out comparison "
                    "potentially contaminated (`drafting/EVALUATION-SETS.md`). Generated by "
                    "`python3 -m jobfilter.audit --exploratory`."),
}


def contrast_with_heldout(sel: dict, dev: dict) -> list:
    """Why the random-reject sample and the held-out set point different ways (added 2026-11-25).

    Uses the v1.0 held-out decisions, opened after v1.1 was frozen (CHANGE.md, c9821188). The held-out set is
    potentially contaminated; this section only compares what kinds of postings each sample contains.
    """
    import collections
    gate = "title has no qualifying role phrase"
    rr = sel["strata"]["random_reject"]["selected"]
    pop = sel["strata"]["random_reject"]["population"]
    rr_gate = sum(1 for k in rr if dev[k]["reasons"][0] == gate)
    pop_gate = sum(1 for k in pop if dev[k]["reasons"][0] == gate)
    held = {d["key"]: d for d in json.loads((HERE / "runs" / VERSION / "heldout-decisions.sealed.json").read_text())}
    labels = read_verdicts(LABELS / "heldout-sheet.csv")
    ys = [k for k, v in labels.items() if v["verdict"] == "Y"]
    y_rej = [k for k in ys if held[k]["decision"] == "REJECT"]
    why = collections.Counter(held[k]["reasons"][0].split('"')[0].strip() for k in y_rej)
    return ["## Why this sample and the held-out set point different ways", "",
            f"The random rejects found 0 wanted postings among those with a Y/N verdict. The held-out set (Ashwin's labels) "
            f"has {len(y_rej)} of {len(ys)} postings labeled Y rejected by {VERSION}. The two samples contain different "
            "kinds of postings:", "",
            f"- **Random rejects:** {rr_gate} of {len(rr)} failed the role gate (no qualifying role phrase). Across all "
            f"{len(pop)} development rejects, {pop_gate} did, so most rejects are sales, legal and other non-engineering "
            "titles, and a random sample mostly re-checks that gate, where wanted postings are rare.",
            "- **Held-out set:** drawn with 20 of 30 postings from engineering-like titles (`jobfilter/heldout.py`), so it "
            "over-samples the postings where the topic, threshold and seniority rules decide. The rejected Y postings' "
            "first reasons: " + "; ".join(f"{r} ({n})" for r, n in why.most_common()) + ".",
            "", "So the random-reject result shows that wanted postings are rare among the mostly non-engineering titles "
            "the filter rejects. It does not show that the filter rarely misses wanted postings. In the held-out set the "
            "misses are engineering-like titles, rejected by the role list as well as by the topic, threshold and "
            "seniority rules. Next time, engineering-titled rejects should be sampled separately. The held-out set is "
            "potentially contaminated (CHANGE.md), so its counts are a pointer, not a measured rate.", ""]


def write_report(source: str = "hand") -> None:
    csv_path, out_name, title, intro = SOURCES[source]
    sel = json.loads(SELECTION.read_text())
    verdicts = read_verdicts(csv_path, allow_blank=True)
    missing = minimum_keys(sel) - set(verdicts)
    if missing:
        raise SystemExit(f"{len(missing)} postings in the minimum sample ({', '.join(MINIMUM_STRATA)}) have no verdict")
    dev = {d["key"]: d for d in json.loads((HERE / "runs" / VERSION / "decisions-dev.json").read_text())}
    t = tally(sel, verdicts, dev)
    L = [title, "", intro, "", "Y = Supriya would want to see it, N = would not, ? = cannot tell from the posting.", "",
         "| Stratum | How chosen | Drawn / population | Y | N | ? | Not judged |", "|---|---|---:|---:|---:|---:|---:|"]
    how = {"random_reject": "random", "kept_random": "random", "close_below": "random among score 6",
           "close_at": "random among score 7", "exclusion_check": "purposive", "review": "all"}
    for name, v in t.items():
        L.append(f"| {name} | {how[name]} | {v['selected']} / {v['population_size']} | {v['Y']} | {v['N']} | {v['?']} | {v['not_judged']} |")

    rr, kr = t["random_reject"], t["kept_random"]
    fn_known = rr["Y"] + rr["N"]
    lo, hi = wilson(rr["Y"], fn_known)
    fp_known = kr["Y"] + kr["N"]
    flo, fhi = wilson(kr["N"], fp_known)
    L += ["", "## What the random samples can say", ""]
    if source != "hand":
        L += ["These counts use AI-assisted verdicts. \"False negative\" and \"false positive\" below mean disagreement "
              "with those verdicts, not with an independent human judgment.", ""]
    L += [
          f"- **Random rejects:** {rr['Y']} of {fn_known} resolved Y/N verdicts disagree with rejection, "
          f"with {rr['?']} unresolved ?. The approximate 95% Wilson interval on resolved verdicts only is "
          f"{pct(lo)} to {pct(hi)}. It excludes unknown outcomes and is not a validated interval for all "
          f"{rr['population_size']} development rejects. Within the drawn sample, treating every ? as N or Y "
          f"gives an error-share range of {pct(rr['Y'] / rr['selected'])} to "
          f"{pct((rr['Y'] + rr['?']) / rr['selected'])}; these are sample sensitivity bounds, not population bounds.",
          f"- **Random kept:** {kr['N']} of {fp_known} resolved Y/N verdicts disagree with KEEP, "
          f"with {kr['?']} unresolved ?. The approximate 95% Wilson interval on resolved verdicts only is "
          f"{pct(flo)} to {pct(fhi)}. In the drawn sample the corresponding unknown-outcome range is "
          f"{pct(kr['N'] / kr['selected'])} to {pct((kr['N'] + kr['?']) / kr['selected'])}. "
          f"The sampling pool contains {kr['population_size']} KEEPs after excluding the selected threshold cases; "
          "this is not an estimate for all KEEPs. Wilson intervals here use a binomial approximation without "
          "finite-population correction. Missing judgments may be systematic, and prior AI exposure can bias labels.",
          "- With about 30 random rejects, a problem affecting a few percent of rejects can easily appear 0 times. "
          "Zero observed errors would not have meant zero errors.", ""]
    L += contrast_with_heldout(sel, dev)
    L += ["## Every audited posting", "",
          "| Key | Title | Strata | Filter | Score | Reason | Verdict | Note |", "|---|---|---|---|---:|---|---|---|"]
    for k in sorted(verdicts, key=lambda k: (sel["categories"][k][0], k)):
        d, v = dev[k], verdicts[k]
        wrong = (d["decision"] == "KEEP" and v["verdict"] == "N") or (d["decision"] == "REJECT" and v["verdict"] == "Y")
        L.append(f"| `{k}` | {d['title']} | {', '.join(sel['categories'][k])} | {d['decision']} | "
                 f"{d.get('score', '')} | {d['reasons'][0]} | **{v['verdict']}**{' (disagrees)' if wrong else ''} | "
                 f"{v['note']} |")
    L += ["", "## Matched words in disagreements (false-friend candidates to judge, not conclusions)", ""]
    for k in sorted(verdicts):
        d, v = dev[k], verdicts[k]
        if (d["decision"] == "KEEP" and v["verdict"] == "N") or (d["decision"] == "REJECT" and v["verdict"] == "Y"):
            L.append(f"- `{k}` {d['title']} ({d['decision']}, verdict {v['verdict']}):")
            for tp in d.get("topics", []):
                L.append(f"  - {tp['group']} via \"{tp['alias']}\": …{tp['snippet']}…")
            loc = d.get("location", {})
            if loc.get("best"):
                L.append(f"  - location read as {loc['best']['kind']} from \"{loc['best']['value']}\"")
    AUDIT.mkdir(exist_ok=True)
    if source == "hand":
        L += ["", "## Later check: a second, blind draw", "",
              "25 of the 30 random rejects above failed the role gate, so this sample could hardly find a real miss. "
              "A further draw of 20 engineering-titled rejects, judged later the same day, is in "
              "`audit/BLIND-EXTRA.md`, with its own sample-size statement and the rows corrected after review."]
    (AUDIT / out_name).write_text("\n".join(L) + "\n")
    print(f"audit/{out_name} written; random rejects Y {rr['Y']}/{fn_known}, kept N {kr['N']}/{fp_known}")
