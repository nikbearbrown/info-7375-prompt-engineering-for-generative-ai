"""Score audit verdicts against filter v1.0 (numbers only, no judgment).

    write_report()                 hand verdicts, labels/audit-sheet.csv          -> audit/REPORT-v1.0.md
    write_report("ai-assisted")    labels/audit-ai-assisted.csv (Codex, from held-out labels)
                                                                                  -> audit/EXPLORATORY-v1.0-ai-assisted.md

Every count has its denominator. Only random strata get an interval; purposive strata are listed, never pooled.
"""
from __future__ import annotations

import json

from .audit import LABELS, SELECTION, VERSION, tally, wilson
from .corpus import HERE, load
from .audit_batches import MINIMUM_STRATA, minimum_keys
from .sheets import read_verdicts

AUDIT = HERE / "audit"


def pct(x):
    return "undefined" if x is None else f"{100 * x:.1f}%"


SOURCES = {
    "hand": (LABELS / "audit-sheet.csv", f"REPORT-{VERSION}.md",
             f"# Reject audit of filter {VERSION}: numbers",
             "Generated by `python3 -m jobfilter.audit --report` from Ashwin's blind hand verdicts in "
             "`labels/audit-sheet.csv`. AI-assisted verdicts (`labels/audit-ai-assisted.csv`, `labels/audit-ai-draft.csv`) "
             "are not read and count toward nothing here."),
    "ai-assisted": (LABELS / "audit-ai-assisted.csv", f"EXPLORATORY-{VERSION}-ai-assisted.md",
                    f"# Exploratory audit of filter {VERSION} with AI-assisted verdicts (not a hand-judged audit)",
                    "**Provenance.** Every verdict here is a Codex suggestion inferred from Ashwin's 30 held-out labels, "
                    "supplied by Ashwin in chat on 2026-11-25 (`labels/audit-ai-assisted.csv`). Ashwin states they are "
                    "not independent hand judgments. The numbers below measure agreement between these AI-assisted "
                    "verdicts and the filter. They are not a human-judged error count. **The brief's requirement is "
                    "unmet:** at least 30 random rejects, the closest calls and a kept sample judged by hand; 0 of 47 "
                    "are. Any rule change based on this file makes the original 30-posting held-out comparison "
                    "potentially contaminated (`drafting/EVALUATION-SETS.md`). Generated by "
                    "`python3 -m jobfilter.audit --exploratory`."),
}


def write_report(source: str = "hand") -> None:
    csv_path, out_name, title, intro = SOURCES[source]
    sel = json.loads(SELECTION.read_text())
    verdicts = read_verdicts(csv_path, allow_blank=True)
    missing = minimum_keys(sel) - set(verdicts)
    if missing:
        raise SystemExit(f"{len(missing)} postings in the minimum sample ({', '.join(MINIMUM_STRATA)}) have no verdict")
    dev = {d["key"]: d for d in json.loads((HERE / "runs" / VERSION / "decisions-dev.json").read_text())}
    t = tally(sel, verdicts, dev)
    L = [title, "", intro, "", "Y = Supriya would want to see it, N = would not, ? = cannot tell from the posting.", "",
         "| Stratum | How chosen | Drawn / population | Y | N | ? | Not judged |", "|---|---|---:|---:|---:|---:|---:|"]
    how = {"random_reject": "random", "kept_random": "random", "close_below": "random among score 6",
           "close_at": "random among score 7", "exclusion_check": "purposive", "review": "all"}
    for name, v in t.items():
        L.append(f"| {name} | {how[name]} | {v['selected']} / {v['population_size']} | {v['Y']} | {v['N']} | {v['?']} | {v['not_judged']} |")

    rr, kr = t["random_reject"], t["kept_random"]
    fn_known = rr["Y"] + rr["N"]
    lo, hi = wilson(rr["Y"], fn_known)
    fp_known = kr["Y"] + kr["N"]
    flo, fhi = wilson(kr["N"], fp_known)
    L += ["", "## What the random samples can say", ""]
    if source != "hand":
        L += ["These counts use AI-assisted verdicts. \"False negative\" and \"false positive\" below mean disagreement "
              "with those verdicts, not with an independent human judgment.", ""]
    L += [
          f"- **Random rejects:** {rr['Y']} of {fn_known} rejects with a Y/N verdict were postings Supriya would want "
          f"(false negatives), with {rr['?']} marked ?. A 95% Wilson interval for that share among the "
          f"{rr['population_size']} development rejects is {pct(lo)} to {pct(hi)}. That is a **sample estimate**, not a "
          "measured rate, and it says nothing about the held-out postings.",
          f"- **Random kept:** {kr['N']} of {fp_known} sampled KEEPs were postings Supriya would not want "
          f"(false positives), with {kr['?']} marked ?. A 95% Wilson interval is {pct(flo)} to {pct(fhi)}, over a population "
          f"of only {kr['population_size']}.",
          "- With about 30 random rejects, a problem affecting a few percent of rejects can easily appear 0 times. "
          "Zero observed errors would not have meant zero errors.", "",
          "## Every audited posting", "",
          "| Key | Title | Strata | Filter | Score | Reason | Verdict | Note |", "|---|---|---|---|---:|---|---|---|"]
    for k in sorted(verdicts, key=lambda k: (sel["categories"][k][0], k)):
        d, v = dev[k], verdicts[k]
        wrong = (d["decision"] == "KEEP" and v["verdict"] == "N") or (d["decision"] == "REJECT" and v["verdict"] == "Y")
        L.append(f"| `{k}` | {d['title']} | {', '.join(sel['categories'][k])} | {d['decision']} | "
                 f"{d.get('score', '')} | {d['reasons'][0]} | **{v['verdict']}**{' (disagrees)' if wrong else ''} | "
                 f"{v['note']} |")
    L += ["", "## Matched words in disagreements (false-friend candidates to judge, not conclusions)", ""]
    for k in sorted(verdicts):
        d, v = dev[k], verdicts[k]
        if (d["decision"] == "KEEP" and v["verdict"] == "N") or (d["decision"] == "REJECT" and v["verdict"] == "Y"):
            L.append(f"- `{k}` {d['title']} ({d['decision']}, verdict {v['verdict']}):")
            for tp in d.get("topics", []):
                L.append(f"  - {tp['group']} via \"{tp['alias']}\": …{tp['snippet']}…")
            loc = d.get("location", {})
            if loc.get("best"):
                L.append(f"  - location read as {loc['best']['kind']} from \"{loc['best']['value']}\"")
    AUDIT.mkdir(exist_ok=True)
    (AUDIT / out_name).write_text("\n".join(L) + "\n")
    print(f"audit/{out_name} written; random rejects Y {rr['Y']}/{fn_known}, kept N {kr['N']}/{fp_known}")
