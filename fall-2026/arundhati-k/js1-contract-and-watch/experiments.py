"""Chapter 1 sampling report and Chapter 2 prompt experiment. Every Claude call is real and logged.

    python3 experiments.py sample                       # 5 dev postings x 4 fresh calls, baseline prompt
    python3 experiments.py run --prompt prompts/baseline.txt --set dev
    python3 experiments.py run --prompt prompts/revision.txt --set dev
    python3 experiments.py run --prompt prompts/baseline.txt --set heldout --final
    python3 experiments.py run --prompt prompts/revision.txt --set heldout --final
    python3 experiments.py score                         # tables from the logs + labeling/labels.csv

Hand labels come only from labeling/labels.csv (column my_label). Held-out runs refuse to start
without --final, and scoring refuses to score any set whose labels are not all filled in.
"""

import argparse
import collections
import csv
import json
import sys
from pathlib import Path

from jsagent import claude_judge, rule
from jsagent.resume import load_resume, skill_fields
from jsagent.watch import load_raw, parse_jobs

HERE = Path(__file__).resolve().parent
RAW = HERE / "evidence" / "raw" / "20261031T061636Z-live.json.gz"  # the response the labeling set came from
LABELS = HERE / "labeling" / "labels.csv"
SAMPLING_LOG = HERE / "experiments" / "sampling" / "calls.jsonl"
PROMPT_LOGS = HERE / "experiments" / "prompt"
SAMPLING_IDS = ["8128744", "8241260", "8333074", "8160776", "8097801"]  # 5 dev postings (README says why)
VALID_LABELS = {"RELEVANT", "NOT RELEVANT"}


def load_labels():
    with open(LABELS) as fh:
        return list(csv.DictReader(fh))


def jobs_by_id():
    return {str(j["id"]): j for j in parse_jobs(load_raw(RAW))}


def sample(args):
    resume, jobs = load_resume(args.resume), jobs_by_id()
    template = claude_judge.load_template(HERE / "prompts" / "baseline.txt")
    for pid in SAMPLING_IDS:
        for k in range(1, args.n + 1):
            r = claude_judge.judge(jobs[pid], resume, template, model=args.model, log_path=SAMPLING_LOG, tag=f"sample {k}")
            print(pid, k, r["verdict"] if r["valid"] else f"INVALID {r['errors'][:1]}")


def run(args):
    if args.set == "heldout" and not args.final:
        sys.exit("refused: the held-out set is run once, at the end. Add --final when the revision is frozen.")
    resume, jobs = load_resume(args.resume), jobs_by_id()
    template = claude_judge.load_template(args.prompt)
    name = Path(args.prompt).stem
    log = PROMPT_LOGS / f"{name}-{args.set}.jsonl"
    for row in load_labels():
        if row["set"] != args.set:
            continue
        r = claude_judge.judge(jobs[row["posting_id"]], resume, template, model=args.model, log_path=log, tag=f"{name} {args.set}")
        print(row["n"], row["posting_id"], r["verdict"] if r["valid"] else f"INVALID {r['errors'][:1]}")


def read_log(path):
    return [json.loads(line) for line in open(path)] if Path(path).exists() else []


def score(args):
    labels = load_labels()
    hand = {r["posting_id"]: r["my_label"].strip().upper() for r in labels}
    skills = skill_fields(load_resume(args.resume))
    jobs = jobs_by_id()
    out = ["# Results (generated by `python3 experiments.py score`)", ""]

    # Sampling
    calls = read_log(SAMPLING_LOG)
    if calls:
        out += ["## Sampling — 5 postings, repeated fresh calls, baseline prompt", "",
                "| posting | title | verdicts in call order | valid | rule (record) | my hand label |", "|---|---|---|---|---|---|"]
        by = collections.defaultdict(list)
        for c in calls:
            by[c["posting_id"]].append(c)
        for pid in SAMPLING_IDS:
            cs = by.get(pid, [])
            verdicts = [c["verdict"] if c["valid"] else "INVALID" for c in cs]
            out.append(f"| {pid} | {jobs[pid]['title'].strip()} | {', '.join(verdicts) or '—'} | "
                       f"{sum(c['valid'] for c in cs)}/{len(cs)} | {rule.judge(jobs[pid], skills)['verdict']} | {hand.get(pid) or '(not labeled)'} |")
        models = sorted({m for c in calls for m in c["models"]})
        out += ["", f"Calls: {len(calls)} · first {calls[0]['asked_at_utc']} · last {calls[-1]['asked_at_utc']} · models reported: {', '.join(models)}", ""]

    # Prompt experiment
    out += ["## Prompt experiment — pass = valid reply AND verdict equals my hand label", "",
            "| prompt | set | passed | invalid replies | n |", "|---|---|---|---|---|"]
    detail = []
    for log in sorted(PROMPT_LOGS.glob("*.jsonl")):
        name, split = log.stem.rsplit("-", 1)
        rows = [r for r in labels if r["set"] == split]
        missing = [r["n"] for r in rows if r["my_label"].strip().upper() not in VALID_LABELS]
        if missing:
            out.append(f"| {name} | {split} | not scored: hand labels missing for rows {', '.join(missing)} | | |")
            continue
        last = {c["posting_id"]: c for c in read_log(log)}  # latest call per posting
        passed = sum(1 for r in rows if last.get(r["posting_id"], {}).get("valid") and last[r["posting_id"]]["verdict"] == hand[r["posting_id"]])
        invalid = sum(1 for r in rows if not last.get(r["posting_id"], {}).get("valid"))
        out.append(f"| {name} | {split} | {passed}/{len(rows)} | {invalid} | {len(rows)} |")
        for r in rows:
            c = last.get(r["posting_id"], {})
            got = c.get("verdict") if c.get("valid") else "INVALID"
            detail.append(f"| {name} | {split} | {r['n']} | {r['posting_id']} | {r['title']} | {hand[r['posting_id']]} | {got} | {'✓' if got == hand[r['posting_id']] else '✗'} |")
    if detail:
        out += ["", "| prompt | set | n | posting | title | my label | Claude (model judgment) | match |", "|---|---|---|---|---|---|---|---|"] + detail
    text = "\n".join(out) + "\n"
    (HERE / "experiments" / "RESULTS.md").parent.mkdir(exist_ok=True)
    (HERE / "experiments" / "RESULTS.md").write_text(text)
    print(text)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--resume", default=str(HERE / "persona" / "rohan-desai.resume.example.json"))
    p.add_argument("--model", default=None)
    sub = p.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("sample")
    s.add_argument("--n", type=int, default=4)
    r = sub.add_parser("run")
    r.add_argument("--prompt", required=True)
    r.add_argument("--set", choices=["dev", "heldout"], required=True)
    r.add_argument("--final", action="store_true")
    sub.add_parser("score")
    args = p.parse_args()
    {"sample": sample, "run": run, "score": score}[args.cmd](args)


if __name__ == "__main__":
    main()
