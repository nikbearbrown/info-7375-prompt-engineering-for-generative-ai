"""JS3 commands: ``uv run python -m job_search_agent.js3 <command>``.

filter        score the whole corpus with FILTER.md; write decisions and a summary
audit-draw    draw the reject-audit sample once and write the blind worksheet
audit-worksheet  re-render the worksheet from the existing draw (no redraw)
audit-report  score the filter against the hand verdicts (pending until they exist)
shortlist     label the claims of every kept posting (FILTER.md §2)
serve         run the MCP tool server on stdin/stdout (see mcp_server.py)
experiment    the one-change-at-a-time measurements (see experiments.py)
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

from job_search_agent.js3 import audit
from job_search_agent.js3.claims import justify
from job_search_agent.js3.corpus import (
    EXCLUDED_BOARDS,
    Corpus,
    load_corpus,
    load_inputs,
)
from job_search_agent.js3.filter import FilterSpec, Scored, load_filter, score
from job_search_agent.resume import default_project_root

V01 = "experiments/js3/filters/FILTER.v0.1.md"
V03 = "experiments/js3/filters/FILTER.v0.3.md"
DRAW = "data/js3/audit/draw.json"
VERDICTS = "experiments/js3/audit/hand_verdicts.json"


def score_all(corpus: Corpus, spec: FilterSpec, root: Path) -> list[Scored]:
    """Scores every corpus posting (FILTER.md §1).

    There are no untitled postings to skip in the collected data, and an untitled one
    is reported by ``cmd_filter``.
    """
    inputs = load_inputs(root)
    return [
        score(e.posting, e.key, e.board, spec, inputs)
        for e in corpus.entries
        if e.posting.title.strip()
    ]


def _write(root: Path, rel: str, content: str | dict[str, Any] | list[Any]) -> None:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    text = (
        content
        if isinstance(content, str)
        else json.dumps(content, indent=2, ensure_ascii=False) + "\n"
    )
    path.write_text(text, encoding="utf-8")
    print(f"wrote {rel}")


def decision_row(s: Scored) -> dict[str, Any]:
    """One posting's decision with every component."""
    return {
        "key": s.key,
        "title": s.posting.title.strip(),
        "location": s.posting.location_name,
        "kept": s.kept,
        "total": s.total,
        "points": s.points,
        "title_basis": s.title_basis,
        "generic_blocker": s.generic_blocker,
        "markers": list(s.markers),
        "skills": [k.term for k in s.skills],
        "topic_words": list(s.topic_words),
        "location_label": s.location.label.value,
        "exclusions": list(s.exclusions),
    }


def cmd_filter(root: Path, filter_path: Path) -> int:
    """Scores the corpus with one filter file; writes the decisions and a summary."""
    spec = load_filter(filter_path)
    corpus = load_corpus(root)
    untitled = [e.key for e in corpus.entries if not e.posting.title.strip()]
    scored = score_all(corpus, spec, root)
    kept = [s for s in scored if s.kept]
    _write(
        root,
        f"data/js3/filter/decisions-v{spec.version}.json",
        {
            "filter_version": spec.version,
            "sources": corpus.raws,
            "missing_sources": corpus.missing,
            "excluded_boards": EXCLUDED_BOARDS,
            "unscorable": untitled,
            "decisions": [decision_row(s) for s in scored],
        },
    )
    per_board = Counter(s.board for s in scored)
    kept_board = Counter(s.board for s in kept)
    lines = [
        f"# Filter run — FILTER.md v{spec.version}",
        "",
        "Generated by `uv run python -m job_search_agent.js3 filter`. "
        "Offline: it reads only the saved raw responses.",
        "",
        "| Board | Raws read | Postings | Kept |",
        "|---|---:|---:|---:|",
        *[
            f"| {b} | {len(corpus.raws.get(b, ()))} | {per_board[b]} "
            f"| {kept_board[b]} |"
            for b in corpus.raws
        ],
        f"| **All** | | **{len(scored)}** | **{len(kept)}** |",
        "",
        f"Missing sources: {corpus.missing or 'none'}. "
        f"Unscorable (no title): {len(untitled)}. "
        f"Excluded boards: "
        + "; ".join(f"`{b}` ({r})" for b, r in EXCLUDED_BOARDS.items())
        + ".",
        "",
        "## Score distribution",
        "",
        "| Score | Postings |",
        "|---:|---:|",
        *[
            f"| {t} | {n} |"
            for t, n in sorted(Counter(max(s.total, -10) for s in scored).items())
        ],
        "",
        "Scores below −10 (two vetoes) are counted at −10.",
        "",
        "## Kept postings",
        "",
        "| Score | Board | Title | Location | Breakdown |",
        "|---:|---|---|---|---|",
        *[
            f"| {s.total} | {s.board} | {s.posting.title.strip()} "
            f"| {s.posting.location_name} | {s.breakdown()} |"
            for s in sorted(kept, key=lambda s: (-s.total, s.board, s.posting.title))
        ],
        "",
    ]
    _write(root, f"docs/js3/filter/FILTER_RUN_v{spec.version}.md", "\n".join(lines))
    return 0


def _versions(root: Path) -> tuple[list[Scored], dict[str, Scored], Corpus]:
    corpus = load_corpus(root)
    v01 = score_all(corpus, load_filter(root / V01), root)
    v03 = {s.key: s for s in score_all(corpus, load_filter(root / V03), root)}
    return v01, v03, corpus


def cmd_audit_worksheet(root: Path) -> int:
    """Re-renders the blind worksheet from the committed draw, in the same order."""
    drawn = json.loads((root / DRAW).read_text(encoding="utf-8"))
    by_key = load_corpus(root).by_key()
    _write(
        root,
        "docs/js3/audit/WORKSHEET.md",
        audit.render_worksheet(drawn["worksheet_order"], by_key),
    )
    return 0


def cmd_audit_draw(root: Path) -> int:
    """Draws the reject-audit sample once; writes the draw, worksheet and template."""
    if (root / DRAW).exists():
        print(f"{DRAW} exists; the audit is drawn once only", file=sys.stderr)
        return 2
    v01, v03, corpus = _versions(root)
    strata = audit.draw(v01, v03)
    order = audit.worksheet_order(strata)
    by_key = corpus.by_key()
    s01 = {s.key: s for s in v01}
    _write(
        root,
        DRAW,
        {
            "seed": audit.SEED,
            "drawn_from": V01,
            "also_scored": V03,
            "strata": strata,
            "worksheet_order": order,
            "scores": {
                k: {"v0.1": decision_row(s01[k]), "v0.3": decision_row(v03[k])}
                for k in order
            },
        },
    )
    _write(root, "docs/js3/audit/WORKSHEET.md", audit.render_worksheet(order, by_key))
    _write(
        root,
        "experiments/js3/audit/hand_verdicts.template.json",
        audit.template(order, by_key),
    )
    return 0


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def cmd_audit_report(root: Path) -> int:
    """Scores both filter versions against the hand verdicts (pending without them)."""
    drawn = json.loads((root / DRAW).read_text(encoding="utf-8"))
    order, strata = drawn["worksheet_order"], drawn["strata"]
    out = "docs/js3/audit/AUDIT_REPORT.md"
    path = root / VERDICTS
    problems = (
        ["no hand_verdicts.json yet"]
        if not path.exists()
        else audit.validate_verdicts(
            json.loads(path.read_text(encoding="utf-8")), order
        )
    )
    if problems:
        _write(
            root,
            out,
            "# Reject audit — PENDING\n\nThe hand verdicts are not complete, "
            "so nothing is reported yet:\n\n"
            + "\n".join(f"- {p}" for p in problems[:20])
            + "\n",
        )
        return 3
    doc = json.loads(path.read_text(encoding="utf-8"))
    verdicts = {v["key"]: v["verdict"] for v in doc["verdicts"]}
    reasons = {v["key"]: v.get("reason", "") for v in doc["verdicts"]}
    sc = drawn["scores"]
    v01, v03, corpus = _versions(root)
    n_rejected = {
        "v0.1": sum(not s.kept for s in v01),
        "v0.3": sum(not s.kept for s in v03.values()),
    }
    n_kept = {
        "v0.1": sum(s.kept for s in v01),
        "v0.3": sum(s.kept for s in v03.values()),
    }
    lines = [
        "# Reject audit — results",
        "",
        f"Hand verdicts by **{doc['judged_by']}** on {doc['judged_on']} "
        f"(`{VERDICTS}`), made on the blind worksheet. "
        "This report is generated from them by "
        "`uv run python -m job_search_agent.js3 audit-report`; "
        "the numbers are recomputable.",
        "",
    ]
    for ver in ("v0.1", "v0.3"):
        kept = {k: sc[k][ver]["kept"] for k in order}
        t = audit.tally(strata, verdicts, kept)
        lines += [
            f"## FILTER {ver}",
            "",
            "| Stratum | n | Filter wrong | Filter right | Cannot tell |",
            "|---|---:|---:|---:|---:|",
        ]
        lines += [
            f"| {name} | {r['n']} | {r['wrong']} | {r['right']} | {r['cannot_tell']} |"
            for name, r in t.items()
        ]
        rr = t["random_rejects"]
        if ver == "v0.1":
            judged = rr["n"] - rr["cannot_tell"]
            k = rr["wrong"]
            lo, hi = audit.clopper_pearson(k, judged) if judged else (0.0, 1.0)
            k_worst = k + rr["cannot_tell"]
            lo_w, hi_w = audit.clopper_pearson(k_worst, rr["n"])
            lines += [
                "",
                f"**Random rejects (v0.1).** I judged {k} of {judged} decided "
                "postings relevant (missed by the filter); "
                f"exact 95% interval for the share of all {n_rejected['v0.1']} "
                "v0.1 rejects that are relevant: "
                f"{_pct(lo)} to {_pct(hi)}, which is roughly "
                f"{round(lo * n_rejected['v0.1'])} to "
                f"{round(hi * n_rejected['v0.1'])} postings, "
                f"against {n_kept['v0.1']} kept. Counting every `CANNOT_TELL` "
                f"as a miss: {k_worst} of {rr['n']}, "
                f"interval {_pct(lo_w)} to {_pct(hi_w)}. This is an estimate "
                f"from {rr['n']} postings, not a measured rate.",
            ]
        lines.append("")
    lines += [
        "## Every posting the filter got wrong (either version)",
        "",
        "| Key | Title | v0.1 | v0.3 | My verdict | My reason |",
        "|---|---|---|---|---|---|",
    ]
    for k in order:
        wrong = [
            ver
            for ver in ("v0.1", "v0.3")
            if verdicts[k] != "CANNOT_TELL"
            and (verdicts[k] == "RELEVANT") != sc[k][ver]["kept"]
        ]
        if wrong:
            lines.append(
                f"| `{k}` | {sc[k]['v0.1']['title']} "
                f"| {'kept' if sc[k]['v0.1']['kept'] else 'rejected'} "
                f"({sc[k]['v0.1']['total']}) | "
                f"{'kept' if sc[k]['v0.3']['kept'] else 'rejected'} "
                f"({sc[k]['v0.3']['total']}) | {verdicts[k]} | {reasons[k]} |"
            )
    lines += [
        "",
        "## The v0.2/v0.3 changes, judged",
        "",
        "| Key | Title | v0.1 → v0.3 | My verdict | Change right? |",
        "|---|---|---|---|---|",
    ]
    for k in strata["changed_or_contested"]:
        a, b = sc[k]["v0.1"]["kept"], sc[k]["v0.3"]["kept"]
        right = (
            "—"
            if verdicts[k] == "CANNOT_TELL" or a == b
            else ("yes" if (verdicts[k] == "RELEVANT") == b else "no")
        )
        lines.append(
            f"| `{k}` | {sc[k]['v0.1']['title']} "
            f"| {'kept' if a else 'rej'} → {'kept' if b else 'rej'} "
            f"| {verdicts[k]} | {right} |"
        )
    lines.append("")
    _write(root, out, "\n".join(lines))
    return 0


def cmd_shortlist(root: Path, filter_path: Path) -> int:
    """Labels the claims of every kept posting; writes the shortlist JSON and page."""
    spec = load_filter(filter_path)
    corpus = load_corpus(root)
    by_key = corpus.by_key()
    kept = sorted(
        (s for s in score_all(corpus, spec, root) if s.kept),
        key=lambda s: (-s.total, s.board, s.posting.title),
    )
    js = [justify(s) for s in kept]
    _write(
        root,
        "data/js3/shortlist.json",
        {
            "filter_version": spec.version,
            "postings": [
                {
                    **j.to_dict(),
                    "score": s.total,
                    "breakdown": s.breakdown(),
                    "url": by_key[s.key].url,
                }
                for s, j in zip(kept, js, strict=True)
            ],
        },
    )
    counts = Counter((c.claim_id, c.label) for j in js for c in j.claims)
    lines = [
        f"# Source-grounded shortlist — FILTER.md v{spec.version}",
        "",
        "Generated by `uv run python -m job_search_agent.js3 shortlist`. "
        "Every claim is labelled by the FILTER.md §2 evidence rules "
        "against the posting's own text; the quote is the span the label rests on. "
        "Labels are computed by code (recomputable), not by Claude.",
        "",
        f"{len(js)} postings, {sum(len(j.claims) for j in js)} claims. "
        'The agent abstained ("I cannot tell") on '
        f"{sum(j.abstained for j in js)} of {len(js)}.",
        "",
        "| Claim | Supported | Contradicted | Insufficient |",
        "|---|---:|---:|---:|",
        *[
            f"| {c} | {counts[(c, 'supported')]} | {counts[(c, 'contradicted')]} "
            f"| {counts[(c, 'insufficient')]} |"
            for c in ("C1", "C2", "C3", "C4", "C5")
        ],
        "",
    ]
    for s, j in zip(kept, js, strict=True):
        lines += [
            f"## {j.title.strip()} — `{j.key}`",
            "",
            f"Score {s.breakdown()} · {by_key[s.key].url}",
            "",
            f"**Answer:** {j.answer}",
            "",
            "| Claim | Label | Field | Quote | Note |",
            "|---|---|---|---|---|",
        ]
        for c in j.claims:
            q = (c.quote or "").replace("|", "\\|")
            lines.append(
                f"| {c.claim_id}: {c.statement} | **{c.label}** "
                f"| {c.field or '—'} | {q or '—'} | {c.note} |"
            )
        lines.append("")
    _write(root, "docs/js3/SHORTLIST.md", "\n".join(lines))
    return 0


def main(argv: list[str] | None = None) -> int:
    """Runs one JS3 command; returns its exit code."""
    parser = argparse.ArgumentParser(prog="python -m job_search_agent.js3")
    parser.add_argument(
        "command",
        choices=[
            "filter",
            "audit-draw",
            "audit-worksheet",
            "audit-report",
            "shortlist",
            "serve",
            "experiment",
        ],
    )
    parser.add_argument(
        "--filter", default="FILTER.md", help="filter file (default FILTER.md)"
    )
    args, rest = parser.parse_known_args(argv)
    root = default_project_root()
    filter_path = root / args.filter
    if args.command == "filter":
        return cmd_filter(root, filter_path)
    if args.command == "audit-worksheet":
        return cmd_audit_worksheet(root)
    if args.command == "audit-draw":
        return cmd_audit_draw(root)
    if args.command == "audit-report":
        return cmd_audit_report(root)
    if args.command == "shortlist":
        return cmd_shortlist(root, filter_path)
    if args.command == "serve":
        from job_search_agent.js3.mcp_server import main as serve_main

        return serve_main(rest)
    from job_search_agent.js3.experiments import main as experiment_main

    return experiment_main(rest)


if __name__ == "__main__":
    raise SystemExit(main())
