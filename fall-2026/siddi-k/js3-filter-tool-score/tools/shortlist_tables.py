"""Write SHORTLIST-CLAIMS.md: every shortlist claim with its labels, generated from claims.jsonl (no hand copying)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from js3 import policy  # noqa: E402

SRC = "output/shortlist/filter-v1/2026-11-26T02-59-56Z/claims.jsonl"


def cell(s) -> str:
    return (s or "").replace("|", "\\|").replace("\n", " ")


def main() -> int:
    rows = [json.loads(x) for x in policy.check_read(SRC).read_text(encoding="utf-8").splitlines() if x.strip()]
    hand = {}
    hp = policy.ROOT / "labels" / "hand_labels.jsonl"
    if hp.exists():
        hand = {x["key"]: x for x in map(json.loads, hp.read_text(encoding="utf-8").splitlines()) if x}
    out = ["# Shortlist claims, every one labelled (generated by tools/shortlist_tables.py from "
           f"`{SRC}`)\n",
           "Claims: Claude (`prompts/justify_v1.md`). Labels: the mechanical quote check, then a separate Claude call "
           "(`prompts/label_claims_v1.md`); the final label follows `js3/evidence.py::final_labels`. Answer: "
           "`js3/evidence.py::answer` (FILTER.md B). Raw stdout: `output/shortlist/filter-v1/<run>/raw/`.\n"]
    for rank, r in enumerate(rows, start=1):
        key = f"{r['board']}:{r['id']}"
        h = hand.get(key)
        hand_txt = f"{h['label']}" + (f" ({h['reason']})" if h and h['reason'] else "") if h else "(not labelled yet)"
        out.append(f"\n## {rank}. {r['title']} ({r['board']}, {r['location']})\n")
        out.append(f"- Filter v1 score: {r['filter_score']} · **Agent's answer: {r['answer']}** ({r['answer_rule']}) · "
                   f"Siddi's blind label: **{hand_txt}**\n")
        out.append("| # | type | claim | quote (verbatim from Claude) | quote check | Claude labeler | **final** |")
        out.append("|---|---|---|---|---|---|---|")
        for c in r["claims"]:
            out.append(f"| {c['i']} | {c['type']} | {cell(c['claim'])} | {cell(c['quote'])} | {c['quote_check']} | "
                       f"{c['claude_label']}: {cell(c['claude_why'])} | **{c['label']}** |")
    policy.write_bytes("output/shortlist/SHORTLIST-CLAIMS.md", ("\n".join(out) + "\n").encode("utf-8"))
    print("wrote output/shortlist/SHORTLIST-CLAIMS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
