"""Flag hand labels that the posting's own text puts in tension with my labeling rule (labels/LABELING_RULE.md).

    python -B scripts/label_flags.py
For every posting I labeled `relevant`, quotes the text behind each rule criterion it may fail:
  criterion 2 (level): a level word in the title; a people-management sentence; a years requirement of 8+
  criterion 1 (work):  a sales / quota / pre-sales sentence
  note rule:           a note that does not name anything in the posting ("partial match")
It reads only the label sheet and the posting text: no filter score, no verdict, no Claude output.
It never changes a label. Writes labels/label_flags.md.
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEVEL = re.compile(r"\b(Staff|Principal|Director|Manager|Head of|VP|Vice President)\b", re.I)
MANAGE = re.compile(r"[^.\n]*\b(manage (a|the|your) team|people manage|direct reports|manag(e|ing) engineers|lead(ing)? a team of|hire,? (and )?(grow|develop)|build and lead)\b[^.\n]*", re.I)
YEARS = re.compile(r"[^.\n]*?\b(\d{1,2})\+?\s*(?:-\s*\d+\s*)?years?\b[^.\n]*", re.I)
NO_REPORTS = re.compile(r"\bno\s+direct\s+reports\b", re.I)   # "no direct reports" is the opposite of managing
SALES = re.compile(r"[^.\n]*\b(quota|pipeline generation|close deals|closing deals|sales cycle|pre-?sales|book of business|revenue targets?|account executives?)\b[^.\n]*", re.I)
VAGUE = re.compile(r"^(partial match|skill ?set matches?|some skills matches?|skills? match(es)?)\.?$", re.I)


def main() -> int:
    sheet = {s["id"]: s for s in json.loads((ROOT / "out" / "audit" / "sheet_blind.json").read_text(encoding="utf-8"))}
    with (ROOT / "labels" / "hand_labels.csv").open(encoding="utf-8", newline="") as f:
        labels = list(csv.DictReader(f))
    out = ["# Label flags: my `relevant` labels beside what each posting's own text says", "",
           "Generated by `scripts/label_flags.py` from the blind sheet and my labels only (no filter output). "
           "A flag is not a correct label; it is the text my labeling rule says to weigh. Every label stays mine.", ""]
    n_flagged = 0
    for row in sorted(labels, key=lambda r: int(r["n"])):
        if row["hand_label"] != "relevant":
            continue
        s = sheet[row["id"]]
        text = s["text"]
        flags = []
        m = LEVEL.search(s["title"])
        if m:
            flags.append(f"criterion 2 (level): title contains **{m.group(1)}**")
        mm = next((m for m in MANAGE.finditer(text) if not NO_REPORTS.search(m.group(0))), None)
        if mm:   # first version matched "no direct reports" in #49 (a false friend in this script); excluded since
            flags.append(f'criterion 2 (people management): "{mm.group(0).strip()[:220]}"')
        yrs = [y for y in YEARS.finditer(text) if int(y.group(1)) >= 8 and int(y.group(1)) < 40]
        if yrs:
            flags.append(f'criterion 2 (8+ years): "{yrs[0].group(0).strip()[:220]}"')
        sm = SALES.search(text)
        if sm:
            flags.append(f'criterion 1 (sales work): "{sm.group(0).strip()[:220]}"')
        if VAGUE.match(row["note"].strip()):
            flags.append(f'note rule: the note "{row["note"]}" does not name what in the posting decided it')
        if flags:
            n_flagged += 1
            out += [f"## #{row['n']} {s['title']} ({s['board']})", f"- my label: **relevant**, note: {row['note']}"]
            out += [f"- {f}" for f in flags] + [""]
    out.insert(4, f"**{n_flagged} of {sum(r['hand_label'] == 'relevant' for r in labels)} `relevant` labels have at least one flag.**\n")
    (ROOT / "labels" / "label_flags.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
