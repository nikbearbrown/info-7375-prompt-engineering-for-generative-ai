"""Run the rule judge on the 20 labeled postings and compare it with my hand labels.

    python3 experiment/rule_vs_hand.py      # writes experiment/rule_vs_hand.md

No network and no Claude call: the rule judge reads the saved baseline response.
"""
import json
import sys
from pathlib import Path

sys.path[:0] = [str(Path(__file__).resolve().parent), str(Path(__file__).resolve().parent.parent)]
from hand_labels import HERE, ROOT, hand_labels, postings, split  # noqa: E402
from agent import rules  # noqa: E402
from agent.resume import load_resume  # noqa: E402


def evidence(verdict):
    """The rule's deciding citation: the failed check's citation, or the R4 skills found."""
    cites = verdict["citations"]
    if verdict["failed_check"]:
        cites = [c for c in cites if c["check"] == verdict["failed_check"]]
    else:
        cites = [c for c in cites if c["check"] == "R4"]
    parts = []
    for c in cites:
        if c["quote"] is None:
            parts.append(f"{c['check']} `{c['posting_field']}` has none of: {', '.join(c['absent_terms'])}")
        else:
            parts.append(f"{c['check']} `{c['posting_field']}`: {c['quote']!r}")
    return "; ".join(parts)


def main():
    resume = load_resume(ROOT / "data" / "resume.example.json")
    requirements = json.loads((ROOT / "data" / "requirements.json").read_text(encoding="utf-8"))
    dev, heldout = split()
    labels = hand_labels()
    if sorted(labels) != sorted(dev + heldout):
        raise SystemExit("refused: labels.csv ids do not match the split")
    jobs = postings()

    rows = []
    for pid in sorted(labels):
        v = rules.evaluate(jobs[pid], resume, requirements)
        hand = labels[pid]
        rows.append((pid, hand, v, hand["my_label"] == v["verdict"],
                     hand["my_failed_check"] == v["failed_check"]))

    agree = sum(r[3] for r in rows)
    agree_check = sum(r[3] and r[4] for r in rows)
    lines = [
        "# Rule judge vs my hand labels (all 20)",
        "",
        "Generated by `experiment/rule_vs_hand.py` from the baseline `runs/2026-10-29-1/raw.json`",
        "(no network, no Claude call). My labels in `labeling/labels.csv` were made blind, before this",
        "comparison, and are not changed by it.",
        "",
        f"- **Label agreement: {agree}/{len(rows)}**",
        f"- Same label and same failed check: {agree_check}/{len(rows)}",
        f"- Development: {sum(r[3] for r in rows if r[1]['set'] == 'dev')}/"
        f"{sum(r[1]['set'] == 'dev' for r in rows)}; held-out: "
        f"{sum(r[3] for r in rows if r[1]['set'] == 'heldout')}/"
        f"{sum(r[1]['set'] == 'heldout' for r in rows)}",
        "",
        "## Disagreements",
        "",
    ]
    diffs = [r for r in rows if not (r[3] and r[4])]
    if not diffs:
        lines.append("None.")
    else:
        lines += ["| posting_id | set | title | my label (failed check) | rule label (failed check) | rule evidence |",
                  "|---|---|---|---|---|---|"]
        for pid, hand, v, same_label, _ in diffs:
            kind = "" if same_label else " **label differs**"
            lines.append(f"| {pid} | {hand['set']} | {v['title']} | {hand['my_label']} "
                         f"({hand['my_failed_check'] or '-'}) | {v['verdict']} ({v['failed_check'] or '-'}){kind} "
                         f"| {evidence(v).replace('|', '/')} |")
    lines += ["", "## All 20", "", "| posting_id | set | my label (check) | rule label (check) | match |",
              "|---|---|---|---|---|"]
    for pid, hand, v, same_label, same_check in rows:
        lines.append(f"| {pid} | {hand['set']} | {hand['my_label']} ({hand['my_failed_check'] or '-'}) | "
                     f"{v['verdict']} ({v['failed_check'] or '-'}) | "
                     f"{'yes' if same_label and same_check else 'label only' if same_label else 'no'} |")
    (HERE / "rule_vs_hand.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"label agreement {agree}/{len(rows)}, label and check {agree_check}/{len(rows)}")


if __name__ == "__main__":
    main()
