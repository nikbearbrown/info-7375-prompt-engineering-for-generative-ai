"""python -m stopline.evaluate data/incidents.json data/evidence.json data/labels.json --out reports/eval_report.md

Compares engine outcomes with hand-written labels and writes a Markdown report.
Misses are listed, not hidden.
"""
import argparse
import json
import platform
from datetime import datetime, timezone

from .cli import load_json_list
from .engine import ENGINE_VERSION, PRECEDENCE, evaluate_all


def build_report(records, labels, evidence_errors, run_at):
    rows, misses = [], []
    for r in records:
        label = labels.get(r["incident_id"], {})
        expected = label.get("expected", "(unlabelled)")
        ok = r["outcome"] == expected
        if not ok:
            misses.append((r, label))
        flag = "yes" if ok else "**MISS**"
        failed = ", ".join(r.get("failed_checks", r["decided_by"])) or "none"
        rows.append(f"| {r['incident_id']} | {expected} | {r['outcome']} | {flag} | {failed} |")

    n, hits = len(records), len(records) - len(misses)
    # Outcomes that would let a lot move or an incident close when it should not.
    unsafe = [m for m, lab in misses
              if PRECEDENCE.index(m["outcome"]) > PRECEDENCE.index(lab.get("expected", m["outcome"]))]

    lines = [
        "# StopLine evaluation report",
        "",
        f"- Run at (UTC): {run_at}",
        f"- Engine version: {ENGINE_VERSION}",
        f"- Python: {platform.python_version()}",
        "- Data: SYNTHETIC, generated by `data/build_synthetic.py`",
        "",
        "## Summary",
        "",
        f"- Cases: {n}",
        f"- Outcome matched label: {hits} / {n}",
        f"- Misses: {len(misses)}, of which less cautious than the label: {len(unsafe)}",
        f"- Evidence records rejected by validation: {len(evidence_errors)}",
        "",
        "Read this with care: the rules and the labels were written by the same author,",
        "against a test set that same author designed. Agreement here shows the rules do",
        "what they were written to do. It does not show they catch problems nobody anticipated.",
        "",
        "## Per case",
        "",
        "| Incident | Label | Engine | Match | Failed checks |",
        "|---|---|---|---|---|",
        *rows,
        "",
        "## Misses",
        "",
    ]
    if not misses:
        lines.append("None.")
    for r, label in misses:
        tag = " (known limitation)" if label.get("known_limitation") else ""
        lines += [
            f"### {r['incident_id']}{tag}",
            "",
            f"- Label: {label.get('expected')} -- {label.get('why')}",
            f"- Engine: {r['outcome']}",
            "",
        ]
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(prog="stopline.evaluate")
    parser.add_argument("incidents")
    parser.add_argument("evidence")
    parser.add_argument("labels")
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)

    records, evidence_errors = evaluate_all(load_json_list(args.incidents), load_json_list(args.evidence))
    with open(args.labels, encoding="utf-8") as fh:
        labels = json.load(fh)
    run_at = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    report = build_report(records, labels, evidence_errors, run_at)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(report)
    print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
